const ARTIST = {"name":"Blood Artist","type":"Creature — Vampire","mana":"{1}{B}","cmc":2,"power":"0","toughness":"1","keywords":[],"colors":["B"],"oracle":"Whenever this creature or another creature dies, target player loses 1 life and you gain 1 life."};

// ─── harness ──────────────────────────────────────────────────────────────────
const P = (id, card, controller = "user", extra = {}) => ({ ...createPermanent({ id, card: { id: `c-${id}`, ...card }, controller, summoningSick: false }), ...extra });
const H = (id, card) => ({ ...card, id });
// Empty libraries, so a library holds exactly what was shuffled into it.
function board({ user = [], ai = [], hand = [], pool = {} } = {}) {
  const g = createGameState({ userDeck: [], aiDeck: [] });
  return { ...g, turn: 5, activePlayer: "user", priorityHolder: "user", phase: "precombat-main", step: "main", stack: [], pendingTriggers: [], consecutivePasses: 0,
    players: { ...g.players,
      user: { ...g.players.user, battlefield: user, hand, manaPool: { ...g.players.user.manaPool, ...pool }, library: [], graveyard: [] },
      ai: { ...g.players.ai, battlefield: ai, hand: [], library: [], graveyard: [] } } };
}
const castsOf = (s, cardId) => legalActionsForPlayer({ ...s, priorityHolder: "user" }, "user").filter((a) => a.kind === "cast-spell" && a.cardId === cardId);
// Cast (the first offer, or the one `pick` chooses) and resolve it — its state-based actions run on resolution.
const cast = (s, cardId, pick = () => true) => {
  const offer = castsOf(s, cardId).find(pick);
  if (!offer) throw new Error(`no cast offer for ${cardId}`);
  return resolveTopOfStack(dispatchAction({ ...s, priorityHolder: "user" }, offer));
};
// The events the death sites log, one per creature, in log order — `by` is the state-based action's cause or the effect's via.
const deathEvents = (s) => s.log.filter((e) => /^creature-(?:dies|exiled-instead|shuffled-instead)$/.test(e.kind))
  .map((e) => ({ kind: e.kind, card: e.cardName, controller: e.controller, by: e.cause || e.via }));
const names = (zone) => zone.map((c) => c.name).sort();
const zones = (s, pid) => ({ library: names(s.players[pid].library), graveyard: names(s.players[pid].graveyard), exile: names(s.players[pid].exile) });
const errors = (s) => s.log.filter((e) => e.kind === "stack-resolve-error").length;
const ev = (kind, card, controller, by) => ({ kind, card, controller, by });

// ─── the combat ───────────────────────────────────────────────────────────────
// The user's Blightsteel Colossus and Grizzly Bears attack; the opponent's Colossus blocks the Colossus and its Bears the Bears.
function colossusTrade({ rip = false } = {}) {
  const s = board({
    user: [P("ubs", BLIGHTSTEEL), P("ub", BEARS), ...(rip ? [P("rip", RIP)] : [])],
    ai: [P("abs", BLIGHTSTEEL, "ai"), P("ab", BEARS, "ai")],
  });
  return resolveCombatDamage({ ...s, phase: "combat", step: "combat-damage", combat: {
    attackers: [{ permanentId: "ubs", attackingPlayer: "user", defender: "ai" }, { permanentId: "ub", attackingPlayer: "user", defender: "ai" }],
    blockers: [{ blockerId: "abs", blockingPlayer: "ai", attackerId: "ubs" }, { blockerId: "ab", blockingPlayer: "ai", attackerId: "ub" }],
  } });
}
// What the self-play runner records for that combat (recordDecisions: true) — the declarations, by name — beside the engine's log.
const DECLARED = [
  { turn: 5, seat: "user", action: { kind: "declare-attacker", name: "Blightsteel Colossus" }, features: { is_active_player: 1 } },
  { turn: 5, seat: "user", action: { kind: "declare-attacker", name: "Grizzly Bears" }, features: { is_active_player: 1 } },
  { turn: 5, seat: "ai", action: { kind: "declare-blocker", name: "Blightsteel Colossus" }, features: { is_active_player: 0 } },
  { turn: 5, seat: "ai", action: { kind: "declare-blocker", name: "Grizzly Bears" }, features: { is_active_player: 0 } },
];
const combatDeaths = (s) => {
  const a = analyzeGame({ decisionTrajectory: { rows: DECLARED }, log: s.log });
  const pick = (m) => ({ attackerDeaths: m.attackerDeaths, blockerDeaths: m.blockerDeaths, otherCombatDeaths: m.otherCombatDeaths });
  return { user: pick(a.user), ai: pick(a.ai) };
};
const summaryDeaths = (s) => s.log.find((e) => e.kind === "combat-damage").deaths;

describe("⭐ Blightsteel Colossus blocked by Blightsteel Colossus: infect takes both to toughness 0, the shuffle takes both away", () => {
  it("both are shuffled into their owners' libraries and logged creature-shuffled-instead (cause combat); the Bears' trade is the only death", () => {
    const s = colossusTrade();
    expect({ events: deathEvents(s), user: zones(s, "user"), ai: zones(s, "ai"), summary: summaryDeaths(s), errors: errors(s) }).toEqual({
      events: [
        ev("creature-shuffled-instead", "Blightsteel Colossus", "user", "combat"),
        ev("creature-dies", "Grizzly Bears", "user", "combat"),
        ev("creature-shuffled-instead", "Blightsteel Colossus", "ai", "combat"),
        ev("creature-dies", "Grizzly Bears", "ai", "combat"),
      ],
      user: { library: ["Blightsteel Colossus"], graveyard: ["Grizzly Bears"], exile: [] },
      ai: { library: ["Blightsteel Colossus"], graveyard: ["Grizzly Bears"], exile: [] },
      summary: ["Grizzly Bears", "Grizzly Bears"],
      errors: 0,
    });
  });

  it("⭐ gameAnalysis counts the Bears' trade as an attacker and a blocker death, and neither Colossus", () => {
    expect(combatDeaths(colossusTrade())).toEqual({
      user: { attackerDeaths: 1, blockerDeaths: 0, otherCombatDeaths: 0 },
      ai: { attackerDeaths: 0, blockerDeaths: 1, otherCombatDeaths: 0 },
    });
  });

  it("⭐ Rest in Peace: the shuffle still applies first — the Colossi are logged creature-shuffled-instead, never exiled; the Bears are exiled (the redirect is live)", () => {
    const s = colossusTrade({ rip: true });
    expect({ events: deathEvents(s), user: zones(s, "user"), ai: zones(s, "ai"), summary: summaryDeaths(s), errors: errors(s) }).toEqual({
      events: [
        ev("creature-shuffled-instead", "Blightsteel Colossus", "user", "combat"),
        ev("creature-exiled-instead", "Grizzly Bears", "user", "combat"),
        ev("creature-shuffled-instead", "Blightsteel Colossus", "ai", "combat"),
        ev("creature-exiled-instead", "Grizzly Bears", "ai", "combat"),
      ],
      user: { library: ["Blightsteel Colossus"], graveyard: [], exile: ["Grizzly Bears"] },
      ai: { library: ["Blightsteel Colossus"], graveyard: [], exile: ["Grizzly Bears"] },
      summary: [],
      errors: 0,
    });
  });

  it("Rest in Peace: gameAnalysis counts no combat death — nothing died", () => {
    const none = { attackerDeaths: 0, blockerDeaths: 0, otherCombatDeaths: 0 };
    expect(combatDeaths(colossusTrade({ rip: true }))).toEqual({ user: none, ai: none });
  });

  it("the replay narrates where each one went", () => {
    const lines = (s) => narrateEngineLog(s.log, { user: "Omnath", ai: "Slivers" }).flatMap((g) => g.lines);
    expect({ plain: lines(colossusTrade()), rip: lines(colossusTrade({ rip: true })) }).toEqual({
      plain: [
        "Blightsteel Colossus is shuffled into its owner's library instead of dying (combat)",
        "Grizzly Bears dies (combat)",
        "Blightsteel Colossus is shuffled into its owner's library instead of dying (combat)",
        "Grizzly Bears dies (combat)",
      ],
      rip: [
        "Blightsteel Colossus is shuffled into its owner's library instead of dying (combat)",
        "Grizzly Bears is exiled instead of dying (combat)",
        "Blightsteel Colossus is shuffled into its owner's library instead of dying (combat)",
        "Grizzly Bears is exiled instead of dying (combat)",
      ],
    });
  });
});

describe("every other death site names it the same way", () => {
  it("⭐ the legend rule (CR 704.5j): a second Progenitus puts the first into the graveyard — it is shuffled away; a second Isamaru's predecessor dies (the control)", () => {
    const run = (rip) => {
      let s = board({ user: [P("prog1", PROGENITUS), P("isa1", ISAMARU), ...(rip ? [P("rip", RIP)] : [])], hand: [H("isa2", ISAMARU), H("prog2", PROGENITUS)],
        pool: { W: 3, U: 2, B: 2, R: 2, G: 2 } });
      s = cast(cast(s, "isa2"), "prog2");
      return { events: deathEvents(s), zones: zones(s, "user"), battlefield: s.players.user.battlefield.map((p) => p.card.name).sort(), errors: errors(s) };
    };
    expect({ plain: run(false), rip: run(true) }).toEqual({
      plain: {
        events: [ev("creature-dies", "Isamaru, Hound of Konda", "user", "legend-rule"), ev("creature-shuffled-instead", "Progenitus", "user", "legend-rule")],
        zones: { library: ["Progenitus"], graveyard: ["Isamaru, Hound of Konda"], exile: [] },
        battlefield: ["Isamaru, Hound of Konda", "Progenitus"], errors: 0,
      },
      rip: {
        events: [ev("creature-exiled-instead", "Isamaru, Hound of Konda", "user", "legend-rule"), ev("creature-shuffled-instead", "Progenitus", "user", "legend-rule")],
        zones: { library: ["Progenitus"], graveyard: [], exile: ["Isamaru, Hound of Konda"] },
        battlefield: ["Isamaru, Hound of Konda", "Progenitus", "Rest in Peace"], errors: 0,
      },
    });
  });

  it("⭐ a destroy (Wrath of God): Progenitus is shuffled away and logged so; the Bears' death is the spell's own event, and under Rest in Peace it is exiled instead", () => {
    const run = (rip) => {
      const s = cast(board({ user: [P("prog", PROGENITUS), P("ub", BEARS), ...(rip ? [P("rip", RIP)] : [])], hand: [H("wrath", WRATH)], pool: { W: 4 } }), "wrath");
      return { events: deathEvents(s), zones: zones(s, "user"), errors: errors(s) };
    };
    expect({ plain: run(false), rip: run(true) }).toEqual({
      plain: { events: [ev("creature-shuffled-instead", "Progenitus", "user", "destroy")],
        zones: { library: ["Progenitus"], graveyard: ["Grizzly Bears", "Wrath of God"], exile: [] }, errors: 0 },
      rip: { events: [ev("creature-shuffled-instead", "Progenitus", "user", "destroy"), ev("creature-exiled-instead", "Grizzly Bears", "user", "destroy")],
        zones: { library: ["Progenitus"], graveyard: [], exile: ["Grizzly Bears", "Wrath of God"] }, errors: 0 },
    });
  });

  it("a death-specific exile is the death site's own move straight to exile, so the event says exiled: the opponent's Progenitus under Misery's Shadow", () => {
    const s = cast(board({ user: [P("shadow", SHADOW)], ai: [P("aprog", PROGENITUS, "ai")], hand: [H("wrath", WRATH)], pool: { W: 4 } }), "wrath");
    expect({ events: deathEvents(s), ai: zones(s, "ai"), user: zones(s, "user"), errors: errors(s) }).toEqual({
      events: [ev("creature-exiled-instead", "Progenitus", "ai", "destroy")],
      ai: { library: [], graveyard: [], exile: ["Progenitus"] },
      user: { library: [], graveyard: ["Misery's Shadow", "Wrath of God"], exile: [] },
      errors: 0,
    });
  });

  it("⭐ a sacrifice (Diabolic Edict): Blightsteel Colossus is shuffled away and logged so, with or without Rest in Peace; an edicted Bears under Rest in Peace is exiled instead (the control)", () => {
    const edict = (victim, rip) => {
      const s = cast(board({ user: rip ? [P("rip", RIP)] : [], ai: [P("av", victim, "ai")], hand: [H("edict", EDICT)], pool: { B: 2 } }), "edict", (a) => a.targets?.[0]?.id === "ai");
      return { events: deathEvents(s), ai: zones(s, "ai"), errors: errors(s) };
    };
    expect({ plain: edict(BLIGHTSTEEL, false), rip: edict(BLIGHTSTEEL, true), bearsRip: edict(BEARS, true) }).toEqual({
      plain: { events: [ev("creature-shuffled-instead", "Blightsteel Colossus", "ai", "sacrifice")], ai: { library: ["Blightsteel Colossus"], graveyard: [], exile: [] }, errors: 0 },
      rip: { events: [ev("creature-shuffled-instead", "Blightsteel Colossus", "ai", "sacrifice")], ai: { library: ["Blightsteel Colossus"], graveyard: [], exile: [] }, errors: 0 },
      bearsRip: { events: [ev("creature-exiled-instead", "Grizzly Bears", "ai", "sacrifice")], ai: { library: [], graveyard: [], exile: ["Grizzly Bears"] }, errors: 0 },
    });
  });

  it("⭐ one sacrifice event (Barter in Blood): the Colossus is shuffled away and logged so; under Rest in Peace the Bears are exiled beside it", () => {
    const run = (rip) => {
      const s = cast(board({ user: [P("ubs", BLIGHTSTEEL), P("ub", BEARS), ...(rip ? [P("rip", RIP)] : [])], ai: [P("ab1", BEARS, "ai"), P("ab2", BEARS, "ai")],
        hand: [H("bb", BARTER)], pool: { B: 4 } }), "bb");
      return { events: deathEvents(s), user: zones(s, "user"), ai: zones(s, "ai"), errors: errors(s) };
    };
    expect({ plain: run(false), rip: run(true) }).toEqual({
      plain: { events: [ev("creature-shuffled-instead", "Blightsteel Colossus", "user", "sacrifice")],
        user: { library: ["Blightsteel Colossus"], graveyard: ["Barter in Blood", "Grizzly Bears"], exile: [] },
        ai: { library: [], graveyard: ["Grizzly Bears", "Grizzly Bears"], exile: [] }, errors: 0 },
      rip: { events: [ev("creature-shuffled-instead", "Blightsteel Colossus", "user", "sacrifice"), ev("creature-exiled-instead", "Grizzly Bears", "user", "sacrifice"),
        ev("creature-exiled-instead", "Grizzly Bears", "ai", "sacrifice"), ev("creature-exiled-instead", "Grizzly Bears", "ai", "sacrifice")],
        user: { library: ["Blightsteel Colossus"], graveyard: [], exile: ["Barter in Blood", "Grizzly Bears"] },
        ai: { library: [], graveyard: [], exile: ["Grizzly Bears", "Grizzly Bears"] }, errors: 0 },
    });
  });

  it("⭐ one sacrifice event meets every replacement on the battlefield as it began (CR 614.1): Dauthi Voidwalker sacrificed beside the opponent's creatures still exiles them, so the log, the zones and the dies triggers agree", () => {
    // The user's victims move before the opponent's, so a Dauthi moved in battlefield order had already left by the time the
    // opponent's creatures moved: they reached the graveyard while their look-backs (and the log) said exiled.
    const s = cast(board({ user: [P("dauthi", DAUTHI), P("ub", BEARS)], ai: [P("ab", BEARS, "ai"), P("aa", ARTIST, "ai")], hand: [H("bb", BARTER)], pool: { B: 4 } }), "bb");
    expect({ events: deathEvents(s), user: zones(s, "user"), aiExile: s.players.ai.exile.map((c) => [c.name, !!c._voidCounter]).sort(), aiGraveyard: names(s.players.ai.graveyard),
      artist: s.stack.filter((o) => o.source?.name === "Blood Artist").length, died: { user: s.players.user.creaturesDiedThisTurn || 0, ai: s.players.ai.creaturesDiedThisTurn || 0 }, errors: errors(s) })
      .toEqual({
        events: [ev("creature-exiled-instead", "Grizzly Bears", "ai", "sacrifice"), ev("creature-exiled-instead", "Blood Artist", "ai", "sacrifice")],
        user: { library: [], graveyard: ["Barter in Blood", "Dauthi Voidwalker", "Grizzly Bears"], exile: [] },
        aiExile: [["Blood Artist", true], ["Grizzly Bears", true]], aiGraveyard: [],
        // The departed Blood Artist sees the two creatures that died (CR 603.10a) — the user's — and not the two exiled.
        artist: 2, died: { user: 2, ai: 0 }, errors: 0,
      });
  });

  it("the destroy site's events narrate their via", () => {
    const s = cast(board({ user: [P("prog", PROGENITUS), P("ub", BEARS), P("rip", RIP)], hand: [H("wrath", WRATH)], pool: { W: 4 } }), "wrath");
    const lines = narrateEngineLog(s.log, { user: "Omnath", ai: "Slivers" }).flatMap((g) => g.lines).filter((l) => /instead of dying|dies/.test(l));
    expect(lines).toEqual([
      "Progenitus is shuffled into its owner's library instead of dying (destroy)",
      "Grizzly Bears is exiled instead of dying (destroy)",
    ]);
  });
});
