/**
 * deathEventKind.test.js — THE DEATH EVENT NAMES WHERE THE CARD WENT (CR 700.4: dies means put into a graveyard from the
 * battlefield).
 *
 * "If <this> would be put into a graveyard from anywhere, reveal <this> and shuffle it into its owner's library instead"
 * (Blightsteel Colossus, Darksteel Colossus, Progenitus) is a replacement at the zone move (gameState.moveCardToZone), and every
 * death site moves its dead toward the graveyard — but the sites named the logged event off the look-back's exile flag alone. A
 * creature shuffled away was logged "creature-dies", a death that never happened; under Rest in Peace, where moveCardToZone applies
 * the shuffle first, "creature-exiled-instead". gameAnalysis counts combat "creature-dies" events as trades, so a shuffled attacker
 * was an attacker death in every reality report. gameState.deathEventKind now names the event at all five sites — the
 * lethal-damage and legend-rule state-based actions, the destroy effect and both sacrifice paths — and the combat damage step's
 * summary lists only the creatures that died.
 *
 * ONE SACRIFICE EVENT MEETS ITS REPLACEMENTS AS IT BEGAN (CR 614.1): the batch sacrifice (Barter in Blood, Living Death) moved its
 * victims in order, so a Dauthi Voidwalker the user sacrificed had left before the opponent's creatures moved — they reached the
 * graveyard while their look-backs, and so the log, said exiled. It now moves the carriers of a graveyard replacement last, as the
 * destroy effect and the lethal-damage state-based action already did (gameState.graveyardReplacementCarriersLast).
 *
 * WHY BLIGHTSTEEL TRADES WITH BLIGHTSTEEL: the printed card is indestructible, so lethal damage never moves it (CR 702.12b) — a
 * lethal-damage fixture on it exercises nothing and passes on the broken code. Damage from a source with infect is -1/-1 counters
 * on a creature (CR 702.90c), so two Colossi that block each other both reach toughness 0 and are put into the graveyard by the
 * state-based action indestructible does not stop (CR 704.5f) — the same chokepoint, destroyLethalCreatures, with cause "combat".
 * A Grizzly Bears trade rides the same combat as the control: a real death the analyzer must still count.
 *
 * Real oracle fixtures (bundled Scryfall, generated by cardIndex.publicCard — never typed by hand). The combat runs through the real
 * damage step (combatResolution.resolveCombatDamage); every other site through the engine's entry points (legalActionsForPlayer →
 * dispatchAction → resolveTopOfStack).
 */
