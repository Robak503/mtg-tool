/**
 * BENDER'S WATERSKIN — the play-weighted program, #558.
 *   "Untap this artifact during each other player's untap step.
 *    {T}: Add one mana of any color."
 *
 * The SELF member of the "during each other player's untap step" family (typeFilteredUntap.js — Seedborn Muse, Murkfiend
 * Liege, Unwinding Clock / Drumbellower / Prophet of Kruphix): during every OTHER player's untap step this permanent untaps too,
 * at the same time as the active player's permanents (the bundled ruling). CR 502.3 — the untap step's turn-based action is the
 * ACTIVE player's; this static adds an untap of the one permanent it is printed on. "This artifact" means that object even if it
 * stops being an artifact (CR 700.7).
 *
 * What keeps it tapped, and what does not (the bundled rulings, 2025-10-02):
 *   · a STUN counter (CR 122.1d — "If a permanent with a stun counter on it would become untapped, instead remove a stun
 *     counter from it") replaces ANY untap, so it holds the Waterskin tapped on an opponent's untap step too;
 *   · "doesn't untap during its controller's untap step" (Inertia Bubble) does NOT apply during another player's untap step —
 *     "These effects won't apply and stop Bender's Waterskin from untapping during another player's untap step."
 * One untap per step: under Seedborn Muse as well, it untaps once (Unwinding Clock's ruling — "you'll only untap your
 * artifacts once"), so a stun counter is removed once, not twice.
 *
 * The same line flips the other printed carrier whose rest is modeled: Thousand Moons Infantry (its whole text). Endbringer untaps
 * the same way (the runtime plays the line on any carrier) but stays parked on its unmodeled "can't attack or block" ability, and
 * Victory Chimes on its "a player of your choice adds {C}".
 *
 * Real oracle fixtures (bundled Scryfall, the 2026-10-01 data, generated by cardIndex.publicCard — never typed by hand).
 */
import { beforeEach, describe, expect, it } from "vitest";
import { _resetIdsForTests, createGameState, createPermanent } from "./gameState.js";
import { legalActionsForPlayer } from "./legalChoices.js";
import { dispatchAction } from "./actionDispatcher.js";
import { nextStep, resolveTopOfStack } from "./gameEngine.js";
import { classifyCard } from "./coverage.js";
import { parseSelfOtherUntap, stripModeledSelfOtherUntap } from "./typeFilteredUntap.js";

beforeEach(() => _resetIdsForTests());

// ─── real card fixtures (generated from the bundled Scryfall data) ──────────────
const WATERSKIN = {"name":"Bender's Waterskin","type":"Artifact","mana":"{3}","cmc":3,"keywords":[],"colors":[],"oracle":"Untap this artifact during each other player's untap step.\n{T}: Add one mana of any color."};
const MANALITH = {"name":"Manalith","type":"Artifact","mana":"{3}","cmc":3,"keywords":[],"colors":[],"oracle":"{T}: Add one mana of any color."}; // the control: the same rock without the untap line
const MIND_STONE = {"name":"Mind Stone","type":"Artifact","mana":"{2}","cmc":2,"keywords":[],"colors":[],"oracle":"{T}: Add {C}.\n{1}, {T}, Sacrifice this artifact: Draw a card."};
const INERTIA_BUBBLE = {"name":"Inertia Bubble","type":"Enchantment — Aura","mana":"{1}{U}","cmc":2,"keywords":["Enchant"],"colors":["U"],"oracle":"Enchant artifact\nEnchanted artifact doesn't untap during its controller's untap step."};
const SEEDBORN = {"name":"Seedborn Muse","type":"Creature — Spirit","mana":"{3}{G}{G}","cmc":5,"power":"2","toughness":"4","keywords":[],"colors":["G"],"oracle":"Untap all permanents you control during each other player's untap step."};
const UNWINDING_CLOCK = {"name":"Unwinding Clock","type":"Artifact","mana":"{4}","cmc":4,"keywords":[],"colors":[],"oracle":"Untap all artifacts you control during each other player's untap step."};
const INFANTRY = {"name":"Thousand Moons Infantry","type":"Creature — Human Soldier","mana":"{2}{W}","cmc":3,"power":"2","toughness":"4","keywords":[],"colors":["W"],"oracle":"Untap this creature during each other player's untap step."};
const ENDBRINGER = {"name":"Endbringer","type":"Creature — Eldrazi","mana":"{5}{C}","cmc":6,"power":"5","toughness":"5","keywords":[],"colors":[],"oracle":"Untap this creature during each other player's untap step.\n{T}: This creature deals 1 damage to any target.\n{C}, {T}: Target creature can't attack or block this turn.\n{C}{C}, {T}: Draw a card."};
const VICTORY_CHIMES = {"name":"Victory Chimes","type":"Artifact","mana":"{3}","cmc":3,"keywords":[],"colors":[],"oracle":"Untap this artifact during each other player's untap step.\n{T}: A player of your choice adds {C}."};
const URBAN_BURGEONING = {"name":"Urban Burgeoning","type":"Enchantment — Aura","mana":"{G}","cmc":1,"keywords":["Enchant"],"colors":["G"],"oracle":"Enchant land\nEnchanted land has \"Untap this land during each other player's untap step.\""};
const GRIZZLY_BEARS = {"name":"Grizzly Bears","type":"Creature — Bear","mana":"{1}{G}","cmc":2,"power":"2","toughness":"2","keywords":[],"colors":["G"],"oracle":""};

// ─── harness ──────────────────────────────────────────────────────────────────
const P = (id, card, controller = "user", extra = {}) => ({ ...createPermanent({ id, card: { id: `c-${id}`, ...card }, controller, summoningSick: false }), ...extra });
const H = (id, card) => ({ ...card, id });
const bears = (who) => [1, 2, 3, 4].map((i) => H(`${who}-lib${i}`, GRIZZLY_BEARS));
function board({ user = [], ai = [], hand = [], active = "user", phase = "precombat-main", step = "main" } = {}) {
  const g = createGameState({ userDeck: [], aiDeck: [] });
  return { ...g, turn: 5, activePlayer: active, priorityHolder: active, phase, step, stack: [], pendingTriggers: [], consecutivePasses: 0,
    players: { ...g.players,
      user: { ...g.players.user, battlefield: user, hand, library: bears("user") },
      ai: { ...g.players.ai, battlefield: ai, hand: [], library: bears("ai") } } };
}
// Step the real engine until `active`'s `step` (the untap step by default), never more than a turn and a half.
function advanceTo(s, active, step = "untap") {
  let next = s;
  for (let i = 0; i < 40; i++) {
    next = nextStep(next);
    if (next.activePlayer === active && next.step === step) return next;
  }
  throw new Error(`never reached ${active}'s ${step} step`);
}
const perm = (s, id, who = "user") => s.players[who].battlefield.find((p) => p.id === id);
const tappedRow = (s, ids, who = "user") => Object.fromEntries(ids.map((id) => [id, perm(s, id, who).tapped]));

describe("⭐ WITNESS — tapped for mana on its controller's turn, it untaps on the opponent's untap step", () => {
  it("paying for Mind Stone taps the Waterskin and the Manalith; on the AI's untap step only the Waterskin untaps", () => {
    const s0 = board({ user: [P("ws", WATERSKIN), P("ml", MANALITH)], hand: [H("ms", MIND_STONE)] });
    const cast = legalActionsForPlayer(s0, "user").find((a) => a.kind === "cast-spell" && a.cardId === "ms");
    expect(cast).toBeTruthy();
    const paid = dispatchAction(s0, cast);
    const resolved = resolveTopOfStack(paid);
    const atAiUntap = advanceTo(resolved, "ai");
    const atUserUntap = advanceTo(atAiUntap, "user");
    const row = {
      afterPayment: tappedRow(paid, ["ws", "ml"]),
      aiUntap: tappedRow(atAiUntap, ["ws", "ml"]),
      userUntap: tappedRow(atUserUntap, ["ws", "ml"]),
      mindStoneEntered: resolved.players.user.battlefield.some((p) => p.card?.name === "Mind Stone"),
    };
    console.log("  WITNESS waterskin", JSON.stringify(row));
    expect(row).toEqual({
      afterPayment: { ws: true, ml: true },
      aiUntap: { ws: false, ml: true },     // the Waterskin untaps with the AI's permanents; the control rock does not
      userUntap: { ws: false, ml: false },  // its controller's own untap step untaps both, as ever
      mindStoneEntered: true,
    });
  });

  it("the untap is logged as the family's extra untap, naming the Waterskin and the step it happened in", () => {
    const s0 = board({ active: "user", phase: "ending", step: "cleanup", user: [P("ws", WATERSKIN, "user", { tapped: true }), P("ml", MANALITH, "user", { tapped: true })] });
    const s = advanceTo(s0, "ai");
    const untapLog = (s.log || []).filter((e) => e.kind === "type-filtered-untap");
    expect({ ws: perm(s, "ws").tapped, ml: perm(s, "ml").tapped, logged: untapLog.map((e) => ({ controller: e.controller, self: e.selfUntapped, during: e.duringUntapOf })) })
      .toEqual({ ws: false, ml: true, logged: [{ controller: "user", self: ["Bender's Waterskin"], during: "ai" }] });
  });
});

describe("what holds it tapped, and what does not", () => {
  it("⭐ not twice on its controller's own untap step: two stun counters lose ONE there (the turn-based untap is the only untap)", () => {
    const s0 = board({ active: "ai", phase: "ending", step: "cleanup", user: [P("ws", WATERSKIN, "user", { tapped: true, counters: { stun: 2 } })] });
    const s = advanceTo(s0, "user");
    expect({ tapped: perm(s, "ws").tapped, stun: perm(s, "ws").counters.stun }).toEqual({ tapped: true, stun: 1 });
  });

  it("⭐ a stun counter replaces the untap on an opponent's untap step too (CR 122.1d) — it stays tapped, the counter goes", () => {
    const s0 = board({ active: "user", phase: "ending", step: "cleanup", user: [P("ws", WATERSKIN, "user", { tapped: true, counters: { stun: 1 } })] });
    const s = advanceTo(s0, "ai");
    expect({ tapped: perm(s, "ws").tapped, stun: perm(s, "ws").counters.stun ?? 0 }).toEqual({ tapped: true, stun: 0 });
  });

  it("⭐ Inertia Bubble holds it through its controller's untap step, and not through the opponent's (the bundled ruling)", () => {
    const bubble = P("ib", INERTIA_BUBBLE, "ai", { attachedTo: "ws" });
    const ws = P("ws", WATERSKIN, "user", { tapped: true, attachments: ["ib"] });
    const s0 = board({ active: "ai", phase: "ending", step: "cleanup", user: [ws], ai: [bubble] });
    const atUser = advanceTo(s0, "user");
    const heldOnOwnStep = perm(atUser, "ws").tapped;
    const atAi = advanceTo(atUser, "ai");
    expect({ heldOnOwnStep, untappedOnOpponentStep: !perm(atAi, "ws").tapped }).toEqual({ heldOnOwnStep: true, untappedOnOpponentStep: true });
  });

  it("⭐ ONE untap per step: under Seedborn Muse a stunned Waterskin loses one counter on the AI's untap step, not two", () => {
    const s0 = board({ active: "user", phase: "ending", step: "cleanup", user: [P("sm", SEEDBORN), P("ws", WATERSKIN, "user", { tapped: true, counters: { stun: 2 } })] });
    const s = advanceTo(s0, "ai");
    expect({ tapped: perm(s, "ws").tapped, stun: perm(s, "ws").counters.stun }).toEqual({ tapped: true, stun: 1 });
  });

  it("ONE untap per step: Unwinding Clock and the Waterskin's own line untap it once — one stun counter, not two", () => {
    const s0 = board({ active: "user", phase: "ending", step: "cleanup", user: [P("uc", UNWINDING_CLOCK), P("ws", WATERSKIN, "user", { tapped: true, counters: { stun: 2 } })] });
    const s = advanceTo(s0, "ai");
    expect({ tapped: perm(s, "ws").tapped, stun: perm(s, "ws").counters.stun }).toEqual({ tapped: true, stun: 1 });
  });

  it("it untaps itself only — the controller's other tapped permanents stay tapped on the opponent's step", () => {
    const s0 = board({ active: "user", phase: "ending", step: "cleanup", user: [P("ws", WATERSKIN, "user", { tapped: true }), P("bear", GRIZZLY_BEARS, "user", { tapped: true })] });
    const s = advanceTo(s0, "ai");
    expect(tappedRow(s, ["ws", "bear"])).toEqual({ ws: false, bear: true });
  });

  it("seat-correct both ways: the AI's Waterskin untaps on the user's step, and only once on its own", () => {
    const s0 = board({ active: "ai", phase: "ending", step: "cleanup", ai: [P("aws", WATERSKIN, "ai", { tapped: true, counters: { stun: 2 } })] });
    const atUser = advanceTo(s0, "user");   // the user's untap step: the AI's Waterskin "untaps" (one stun counter goes)
    const stunAfterUserStep = perm(atUser, "aws", "ai").counters.stun;
    const atAi = advanceTo(atUser, "ai");   // the AI's own untap step: the turn-based untap only (the last counter goes)
    expect({ stunAfterUserStep, stunAfterOwnStep: perm(atAi, "aws", "ai").counters.stun ?? 0, tapped: perm(atAi, "aws", "ai").tapped })
      .toEqual({ stunAfterUserStep: 1, stunAfterOwnStep: 0, tapped: true });
  });
});

describe("the other printed carriers of the line", () => {
  it("⭐ Thousand Moons Infantry: tapped, it untaps on the opponent's untap step — and its summoning sickness is NOT cleared there", () => {
    const s0 = board({ active: "user", phase: "ending", step: "cleanup", user: [P("tmi", INFANTRY, "user", { tapped: true, summoningSick: true })] });
    const s = advanceTo(s0, "ai");
    expect({ tapped: perm(s, "tmi").tapped, summoningSick: perm(s, "tmi").summoningSick }).toEqual({ tapped: false, summoningSick: true });
  });

  it("Endbringer (parked on another ability) untaps on the opponent's untap step all the same — the runtime reads the line on any carrier", () => {
    const s0 = board({ active: "user", phase: "ending", step: "cleanup", user: [P("eb", ENDBRINGER, "user", { tapped: true })] });
    expect(perm(advanceTo(s0, "ai"), "eb").tapped).toBe(false);
  });
});

describe("the recognizer — the printed line, whole, and nothing else", () => {
  it("reads the self line on Waterskin, Infantry, Endbringer and Victory Chimes", () => {
    expect([WATERSKIN, INFANTRY, ENDBRINGER, VICTORY_CHIMES].map((c) => parseSelfOtherUntap(c))).toEqual([true, true, true, true]);
  });

  it("CREED — a quoted grant (Urban Burgeoning), a group untap (Seedborn), a conditional and a 'your untap step' line are not the self line", () => {
    expect(parseSelfOtherUntap(URBAN_BURGEONING)).toBe(false);
    expect(parseSelfOtherUntap(SEEDBORN)).toBe(false);
    expect(parseSelfOtherUntap({ oracle: "Untap this artifact during each other player's untap step if you control a Plains." })).toBe(false);
    expect(parseSelfOtherUntap({ oracle: "Untap this artifact during your untap step." })).toBe(false);
  });

  it("the metric strip removes exactly the printed line and gives back the rest", () => {
    expect(stripModeledSelfOtherUntap(WATERSKIN.oracle)).toBe("{T}: Add one mana of any color.");
    expect(stripModeledSelfOtherUntap(URBAN_BURGEONING.oracle)).toBe(URBAN_BURGEONING.oracle);
  });
});

describe("classification — what flips and what honestly doesn't", () => {
  it("⭐ Bender's Waterskin is native-mana; Thousand Moons Infantry is native", () => {
    expect(classifyCard(WATERSKIN)).toBe("native-mana");
    expect(classifyCard(INFANTRY)).toMatch(/^native-/);
  });

  it("Endbringer stays parked — its '{C}, {T}: Target creature can't attack or block this turn.' is unmodeled", () => {
    expect(classifyCard(ENDBRINGER)).toBe("body-only");
  });

  it("Victory Chimes stays parked — its mana goes to a player of your choice, unmodeled", () => {
    expect(classifyCard(VICTORY_CHIMES)).not.toMatch(/^native-/);
  });

  it("Urban Burgeoning stays parked — the line is a quoted grant to the enchanted land, a different ability", () => {
    expect(classifyCard(URBAN_BURGEONING)).not.toMatch(/^native-/);
  });

  it("REGRESSION PIN — the group members still classify through their own hooks", () => {
    expect(classifyCard(SEEDBORN)).toBe("native-static");
    expect(classifyCard(UNWINDING_CLOCK)).toBe("native-static");
    expect(classifyCard(MANALITH)).toBe("native-mana");
  });
});
