// ─── the board: the AI ("ai") in its own precombat main, one opponent ("user") ──
let seq = 0;
const perm = (card, controller, id) => {
  seq += 1;
  return createPermanent({ id: id || `${controller}-p${seq}`, card: { ...card, id: `${controller}-c${seq}` }, controller, tapped: false, summoningSick: false });
};
const gyCard = (card, owner, id) => ({ ...card, id });

function aiMain({ aura, mana, board = [], oppBoard = [], graveyard = [], oppGraveyard = [] }) {
  const b = createGameState({ userDeck: [], aiDeck: [] });
  return { ...b, activePlayer: "ai", priorityHolder: "ai", phase: "precombat-main", step: "main",
    players: { ...b.players,
      ai: { ...b.players.ai, hand: [{ ...aura, id: "aura1" }], battlefield: board, graveyard, manaPool: { ...b.players.ai.manaPool, ...mana } },
      user: { ...b.players.user, battlefield: oppBoard, graveyard: oppGraveyard },
    } };
}

/** The AI's pick, as what it did with the Aura: the enchanted object's name and side, or "held". */
function auraPick(s, seat = "ai") {
  const pick = pickAction(s, seat, legalActionsForPlayer(s, seat), { archetype: "midrange" });
  if (pick?.kind !== "cast-spell" || pick.cardId !== "aura1") return "held";
  const t = pick.targets[0];
  if (t.type === "player") return `player ${t.id}`;
  return `${t.name} (${t.controller})`;
}

describe("the curse reading (playerAuraEffect) — what a player Aura's triggers do to the enchanted player", () => {
  it("Fraying Sanity's trigger parses to the enchanted player's mill: an opponent's Aura, ranked by library size", () => {
    expect(playerAuraEffect(FRAYING_SANITY)).toBe(ENCHANTED_PLAYER_EFFECTS["enchanted-gy-mill"]);
    expect(ENCHANTED_PLAYER_EFFECTS["enchanted-gy-mill"].side).toBe("enemy");
  });

  it("a player Aura whose trigger the engine does not read has no side — Curse of Opulence (its Gold tokens are the attackers'), Paradox Haze (an extra upkeep you want for yourself)", () => {
    expect({ opulence: playerAuraEffect(CURSE_OF_OPULENCE), haze: playerAuraEffect(PARADOX_HAZE) }).toEqual({ opulence: null, haze: null });
  });
});

describe("an Aura that enchants a player goes on the side its trigger hurts", () => {
  it("⭐ Fraying Sanity (the enchanted player mills) goes on the opponent — the AI used to enchant itself", () => {
    const s = aiMain({ aura: FRAYING_SANITY, mana: { U: 3 } });
    // Both players are offered (CR 303.4a — an Aura spell targets what it will enchant); the pick is the opponent.
    const offered = legalActionsForPlayer(s, "ai").filter((a) => a.cardId === "aura1").map((a) => a.targets[0].id).sort();
    expect({ offered, pick: auraPick(s) }).toEqual({ offered: ["ai", "user"], pick: "player user" });
  });

  it("with the opponent untargetable (Leyline of Sanctity), it is held — never cast on the AI", () => {
    const s = aiMain({ aura: FRAYING_SANITY, mana: { U: 3 }, oppBoard: [perm(LEYLINE, "user")] });
    const offered = legalActionsForPlayer(s, "ai").filter((a) => a.cardId === "aura1").map((a) => a.targets[0].id);
    expect({ offered, pick: auraPick(s) }).toEqual({ offered: ["ai"], pick: "held" });
  });

  it("in a pod it goes on the opponent with the fewest cards in library — the one a mill brings closest to losing (CR 704.5b)", () => {
    const b = createGameState({ userDeck: [], aiDeck: [], opponentDecks: [[], [], []], mode: "commander" });
    const seats = Object.keys(b.players);
    const me = seats.includes("ai1") ? "ai1" : "ai";
    const others = seats.filter((p) => p !== me);
    const library = (pid, n) => Array.from({ length: n }, (_, i) => ({ ...FOREST, id: `${pid}-lib${i}` }));
    const sizes = [30, 12, 25];
    const players = { ...b.players };
    players[me] = { ...players[me], hand: [{ ...FRAYING_SANITY, id: "aura1" }], manaPool: { ...players[me].manaPool, U: 3 }, library: library(me, 40) };
    others.forEach((pid, i) => { players[pid] = { ...players[pid], library: library(pid, sizes[i]) }; });
    const s = { ...b, activePlayer: me, priorityHolder: me, phase: "precombat-main", step: "main", players };
    expect(auraPick(s, me)).toBe(`player ${others[1]}`);
  });
});

describe("an Aura whose host is not only a creature takes its side from the shared intent reader", () => {
  it("⭐ Petrify (can't attack or block, no activated abilities) locks the opponent's biggest artifact or creature — it used to lock the AI's own", () => {
    const s = aiMain({ aura: PETRIFY, mana: { W: 2 },
      board: [perm(MIND_STONE, "ai"), perm(BEARS, "ai")], oppBoard: [perm(MIND_STONE, "user"), perm(WURM, "user")] });
    expect(auraPick(s)).toBe("Craw Wurm (user)");
  });

  it("Petrify with only the AI's own artifacts and creatures to enchant is held", () => {
    const s = aiMain({ aura: PETRIFY, mana: { W: 2 }, board: [perm(MIND_STONE, "ai"), perm(BEARS, "ai")], oppBoard: [perm(FOREST, "user")] });
    expect(auraPick(s)).toBe("held");
  });

  it("⭐ Suppression Bonds (enchant nonland permanent) locks the opponent's Sol Ring when it has no creature — never the AI's Mind Stone or Bears", () => {
    const s = aiMain({ aura: SUPPRESSION_BONDS, mana: { W: 4 },
      board: [perm(MIND_STONE, "ai"), perm(BEARS, "ai")], oppBoard: [perm(FOREST, "user"), perm(SOL_RING, "user")] });
    expect(auraPick(s)).toBe("Sol Ring (user)");
  });

  it("Relic Ward (the enchanted artifact has shroud) protects the AI's own artifact; with only the opponent's, it is held", () => {
    const both = aiMain({ aura: RELIC_WARD, mana: { W: 2 }, board: [perm(MIND_STONE, "ai")], oppBoard: [perm(SOL_RING, "user")] });
    const oppOnly = aiMain({ aura: RELIC_WARD, mana: { W: 2 }, oppBoard: [perm(SOL_RING, "user")] });
    expect({ both: auraPick(both), oppOnly: auraPick(oppOnly) }).toEqual({ both: "Mind Stone (ai)", oppOnly: "held" });
  });

  it("Aether Meltdown (-4/-0 on a creature or Vehicle) shrinks the opponent's biggest creature, never the AI's", () => {
    const s = aiMain({ aura: AETHER_MELTDOWN, mana: { U: 2 },
      board: [perm(WURM, "ai")], oppBoard: [perm(BEARS, "user"), perm(GIANT, "user")] });
    expect(auraPick(s)).toBe("Hill Giant (user)");
  });

  it("Ice Over (doesn't untap — a curse since 2026-10-17, auraEntry's untap-lock reading; aiEntersTriggerHold.test.js) locks the opponent's Craw Wurm — it used to be held", () => {
    const s = aiMain({ aura: ICE_OVER, mana: { U: 2 },
      board: [perm(MIND_STONE, "ai"), perm(BEARS, "ai")], oppBoard: [perm(MIND_STONE, "user"), perm(WURM, "user")] });
    expect(auraPick(s)).toBe("Craw Wurm (user)");
  });
});

describe("Animate Dead takes the biggest creature card in any graveyard — it returns under the caster's control either way", () => {
  it("⭐ the opponent's Craw Wurm over the AI's Grizzly Bears; the AI's Wurm over the opponent's Hill Giant", () => {
    const theirs = aiMain({ aura: ANIMATE_DEAD, mana: { B: 2 }, graveyard: [gyCard(BEARS, "ai", "a-gy-bears")], oppGraveyard: [gyCard(WURM, "user", "u-gy-wurm")] });
    const ours = aiMain({ aura: ANIMATE_DEAD, mana: { B: 2 }, graveyard: [gyCard(WURM, "ai", "a-gy-wurm")], oppGraveyard: [gyCard(GIANT, "user", "u-gy-giant")] });
    expect({ theirs: auraPick(theirs), ours: auraPick(ours) }).toEqual({ theirs: "Craw Wurm (user)", ours: "Craw Wurm (ai)" });
  });
});

describe("the lanes that offer only the caster's own lands keep the land rule", () => {
  it("Wild Growth goes on the AI's Forest; Squirrel Nest (a granted ability, offered on the AI's own lands only) too", () => {
    const wild = aiMain({ aura: WILD_GROWTH, mana: { G: 1 }, board: [perm(FOREST, "ai")], oppBoard: [perm(FOREST, "user")] });
    const nest = aiMain({ aura: SQUIRREL_NEST, mana: { G: 3 }, board: [perm(FOREST, "ai")], oppBoard: [perm(FOREST, "user")] });
    expect({ wild: auraPick(wild), nest: auraPick(nest) }).toEqual({ wild: "Forest (ai)", nest: "Forest (ai)" });
  });
});
