/**
 * splitHalfColors.test.js — a split card cast as one half, or an adventurer cast as its Adventure, is on the stack with ONLY that
 * half's characteristics, its colours among them.
 *
 * The rules (bundled CR): a player chooses which half of a split card they are casting before putting it onto the stack (CR
 * 709.3); while on the stack, only the characteristics of the half being cast exist (CR 709.3b). In every other zone the two
 * halves combine, and "a split card's colors and mana value are determined from its combined mana cost" (CR 709.4b). An
 * adventurer is played normally or as an Adventure (CR 715.3); on the stack as an Adventure it has only its alternative
 * characteristics (CR 715.3b), and everywhere else only its normal ones (CR 715.4). An object is the colour of the mana symbols
 * in its mana cost (CR 202.2). A fused split spell is the one exception: it has the combined characteristics of its two halves
 * (CR 702.102b, 709.4d) — the engine never offers the fused cast (fuseSplitCard.test.js), so that read is pinned on the combined
 * card below.
 *
 * THE BUG (probed 2026-10-17): splitCard.splitFaceCards and adventure.adventureFaceCard spread the whole card into the projected
 * face, so the face kept the card's `colors`. Fire, cast from Fire // Ice, was red AND blue: Gainsay ("Counter target blue
 * spell") and Pyroblast could counter it, Kor Firewalker ("Whenever a player casts a red spell") gained life on Ice, and Ice could
 * not tap Kor Firewalker (protection from red). Blow Off Steam — the red Adventure of the blue Frolicking Familiar, whose card the
 * data records as blue (its normal colour, CR 715.4) — was cast BLUE: Gainsay and Pyroblast could counter it, it could be aimed
 * at Kor Firewalker through protection from red, and Kor Firewalker never saw a red spell.
 *
 * Every reader takes the colours off the stack object's source, the projected face (spellOnStack.counterColorsOf for the counter
 * filters and Pyroblast/Hydroblast's restricted twins, layers.colorsOf for the cast watchers, the cast offer's protection read and
 * the resolution re-check), so the face carrying the half's own colours fixes them together.
 *
 * Real oracle fixtures (bundled Scryfall snapshot, generated by cardIndex.publicCard — never typed by hand).
 */
import { beforeEach, describe, expect, it } from "vitest";
import { _resetIdsForTests, createGameState, createPermanent } from "./gameState.js";
import { legalActionsForPlayer } from "./legalChoices.js";
import { dispatchAction } from "./actionDispatcher.js";
import { resolveTopOfStack } from "./gameEngine.js";
import { splitFaceCards } from "./splitCard.js";
import { adventureFaceCard, permanentFaceCard } from "./adventure.js";
import { spellMatchesCounterFilter } from "./spellOnStack.js";

beforeEach(() => _resetIdsForTests());

// ─── real card fixtures (generated from the bundled Scryfall data) ──────────────
const FIRE_ICE = {"name":"Fire // Ice","type":"Instant // Instant","mana":"{1}{R} // {1}{U}","cmc":4,"keywords":[],"layout":"split","colors":["R","U"],"oracle":"Fire - Instant {1}{R}\nFire deals 2 damage divided as you choose among one or two targets.\n//\nIce - Instant {1}{U}\nTap target permanent.\nDraw a card."}; // native-spell
const RESPONSE_RESURGENCE = {"name":"Response // Resurgence","type":"Instant // Sorcery","mana":"{R/W}{R/W} // {3}{R}{W}","cmc":7,"keywords":[],"layout":"split","colors":["R","W"],"oracle":"Response - Instant {R/W}{R/W}\nResponse deals 5 damage to target attacking or blocking creature.\n//\nResurgence - Sorcery {3}{R}{W}\nCreatures you control gain first strike and vigilance until end of turn. After this main phase, there is an additional combat phase followed by an additional main phase."}; // native-spell
const TURN_BURN = {"name":"Turn // Burn","type":"Instant // Instant","mana":"{2}{U} // {1}{R}","cmc":5,"keywords":["Fuse"],"layout":"split","colors":["R","U"],"oracle":"Turn - Instant {2}{U}\nUntil end of turn, target creature loses all abilities and becomes a red Weird with base power and toughness 0/1.\nFuse (You may cast one or both halves of this card from your hand.)\n//\nBurn - Instant {1}{R}\nBurn deals 2 damage to any target.\nFuse (You may cast one or both halves of this card from your hand.)"}; // arbiter-spell
const FROLICKING_FAMILIAR = {"name":"Frolicking Familiar // Blow Off Steam","type":"Creature — Otter Wizard // Instant — Adventure","mana":"{2}{U} // {R}","cmc":3,"keywords":["Flying"],"layout":"adventure","colors":["U"],"oracle":"Frolicking Familiar - Creature — Otter Wizard {2}{U}\nFlying\nWhenever you cast an instant or sorcery spell, this creature gets +1/+1 until end of turn.\n//\nBlow Off Steam - Instant — Adventure {R}\nBlow Off Steam deals 1 damage to any target. (Then exile this card. You may cast the creature later from exile.)","power":"2","toughness":"2"}; // native-mixed
const SCALDING_VIPER = {"name":"Scalding Viper // Steam Clean","type":"Creature — Elemental Snake // Sorcery — Adventure","mana":"{1}{R} // {1}{U}","cmc":2,"keywords":[],"layout":"adventure","colors":["R"],"oracle":"Scalding Viper - Creature — Elemental Snake {1}{R}\nWhenever an opponent casts a spell with mana value 3 or less, this creature deals 1 damage to that player.\n//\nSteam Clean - Sorcery — Adventure {1}{U}\nReturn target nonland permanent to its owner's hand. (Then exile this card. You may cast the creature later from exile.)","power":"2","toughness":"1"}; // native-mixed
const GAINSAY = {"name":"Gainsay","type":"Instant","mana":"{1}{U}","cmc":2,"keywords":[],"colors":["U"],"oracle":"Counter target blue spell."}; // native-spell
const PYROBLAST = {"name":"Pyroblast","type":"Instant","mana":"{R}","cmc":1,"keywords":[],"colors":["R"],"oracle":"Choose one —\n• Counter target spell if it's blue.\n• Destroy target permanent if it's blue."}; // native-spell
const HYDROBLAST = {"name":"Hydroblast","type":"Instant","mana":"{U}","cmc":1,"keywords":[],"colors":["U"],"oracle":"Choose one —\n• Counter target spell if it's red.\n• Destroy target permanent if it's red."}; // native-spell
const KOR_FIREWALKER = {"name":"Kor Firewalker","type":"Creature — Kor Soldier","mana":"{W}{W}","cmc":2,"keywords":["Protection"],"colors":["W"],"oracle":"Protection from red\nWhenever a player casts a red spell, you may gain 1 life.","power":"2","toughness":"2"}; // native-trigger
const LIGHTNING_BOLT = {"name":"Lightning Bolt","type":"Instant","mana":"{R}","cmc":1,"keywords":[],"colors":["R"],"oracle":"Lightning Bolt deals 3 damage to any target."}; // native-spell
const BEARS = {"name":"Grizzly Bears","type":"Creature — Bear","mana":"{1}{G}","cmc":2,"keywords":[],"colors":["G"],"oracle":"","power":"2","toughness":"2"}; // native-body

// ─── harness ──────────────────────────────────────────────────────────────────
const H = (id, card) => ({ ...card, id });
const P = (id, card, controller) => createPermanent({ id, card: { ...card, id: `c-${id}` }, controller, summoningSick: false });
/** A two-seat table in `active`'s precombat main; each seat's hand / battlefield / pool / library given. */
function board({ active = "ai", user = {}, ai = {} } = {}) {
  const g = createGameState({ userDeck: [], aiDeck: [] });
  const lib = (who) => [1, 2, 3].map((i) => ({ ...BEARS, id: `${who}-lib${i}` }));
  const seat = (who, o) => ({ ...g.players[who], battlefield: o.battlefield || [], hand: o.hand || [], graveyard: [], exile: [],
    manaPool: { ...g.players[who].manaPool, ...(o.pool || {}) }, library: o.library || lib(who) });
  return { ...g, turn: 5, activePlayer: active, priorityHolder: active, phase: "precombat-main", step: "main", stack: [], pendingTriggers: [], consecutivePasses: 0,
    players: { ...g.players, user: seat("user", user), ai: seat("ai", ai) } };
}
const castsOf = (s, who, cardId) => legalActionsForPlayer({ ...s, priorityHolder: who }, who).filter((a) => a.kind === "cast-spell" && a.cardId === cardId);
/** Dispatch `who`'s one offered cast of `cardId` that `pick` accepts (the cast must be offered — the test fails otherwise). */
function cast(s, who, cardId, pick = () => true) {
  const a = castsOf(s, who, cardId).find(pick);
  expect(a, `${who} is offered a cast of ${cardId}`).toBeTruthy();
  return dispatchAction({ ...s, priorityHolder: who }, a);
}
const named = (name) => (a) => (a.faceCard?.name ?? a.name) === name;
const spellNamed = (s, name) => s.stack.find((o) => o.kind === "spell" && o.source?.name === name);
const triggersFrom = (s, name) => s.stack.filter((o) => o.kind === "triggered-ability" && (o.source?.name ?? o.source?.card?.name) === name);
const targetsId = (id) => (a) => (a.targets || []).some((t) => t.id === id);

// The user answers with each colour counter: Gainsay ("counter target blue spell"), Pyroblast ("if it's blue") and Hydroblast
// ("if it's red") — the two blasts read as their restricted twins (effects/parser.js).
const ANSWERS = [H("gs", GAINSAY), H("pb", PYROBLAST), H("hb", HYDROBLAST)];
const ANSWER_POOL = { U: 2, R: 1, C: 1 };
/** Which of the three answers the user is offered against the stack spell named `name`. */
function answersAgainst(s, name) {
  const spell = spellNamed(s, name);
  expect(spell, `${name} is on the stack`).toBeTruthy();
  return ["gs", "pb", "hb"].filter((id) => castsOf(s, "user", id).some(targetsId(spell.id)));
}
/** The AI casts `card` (the offer `pick` accepts) into the user's three answers. */
const castIntoAnswers = (card, pick) =>
  cast(board({ ai: { hand: [card], pool: { R: 1, U: 1, C: 2 } }, user: { battlefield: [P("ub", BEARS, "user")], hand: ANSWERS, pool: ANSWER_POOL } }), "ai", card.id, pick);

// ─── the counters ───────────────────────────────────────────────────────────────
describe("a counter's colour filter reads the half on the stack (CR 709.3b, 715.3b)", () => {
  it("⭐ Fire is red: Hydroblast may counter it — Gainsay and Pyroblast may not", () => {
    expect(answersAgainst(castIntoAnswers(H("fi", FIRE_ICE), named("Fire")), "Fire")).toEqual(["hb"]);
  });

  it("⭐ Ice is blue: Gainsay and Pyroblast may counter it — Hydroblast may not", () => {
    expect(answersAgainst(castIntoAnswers(H("fi", FIRE_ICE), named("Ice")), "Ice")).toEqual(["gs", "pb"]);
  });

  it("Gainsay resolves against Ice: Ice is countered and the whole card goes to the graveyard (CR 709.4)", () => {
    const s = castIntoAnswers(H("fi", FIRE_ICE), named("Ice"));
    const after = resolveTopOfStack(cast(s, "user", "gs", targetsId(spellNamed(s, "Ice").id)));
    expect(spellNamed(after, "Ice")).toBeUndefined();
    expect(after.players.ai.graveyard.map((c) => c.name)).toEqual(["Fire // Ice"]);
  });

  it("⭐ Blow Off Steam — the red Adventure of a blue card — is red: Hydroblast, never Gainsay or Pyroblast", () => {
    const s = castIntoAnswers(H("ff", FROLICKING_FAMILIAR), (a) => a.adventureCast);
    expect(answersAgainst(s, "Blow Off Steam")).toEqual(["hb"]);
  });

  it("⭐ Steam Clean — the blue Adventure of a red card — is blue: Gainsay and Pyroblast, never Hydroblast", () => {
    const s = castIntoAnswers(H("sv", SCALDING_VIPER), (a) => a.adventureCast);
    expect(answersAgainst(s, "Steam Clean")).toEqual(["gs", "pb"]);
  });

  it("control: the adventurer cast normally has its normal colour (CR 715.4) — Frolicking Familiar is blue", () => {
    const s = cast(board({ ai: { hand: [H("ff", FROLICKING_FAMILIAR)], pool: { U: 1, C: 2 } }, user: { hand: ANSWERS, pool: ANSWER_POOL } }), "ai", "ff", (a) => !a.adventureCast);
    expect(answersAgainst(s, "Frolicking Familiar")).toEqual(["gs", "pb"]);
  });

  it("control: an ordinary red spell — Lightning Bolt — meets Hydroblast only", () => {
    const s = cast(board({ ai: { hand: [H("lb", LIGHTNING_BOLT)], pool: { R: 1 } }, user: { hand: ANSWERS, pool: ANSWER_POOL } }), "ai", "lb", targetsId("user"));
    expect(answersAgainst(s, "Lightning Bolt")).toEqual(["hb"]);
  });

  it("control: a fused split spell (both halves' colours, CR 702.102b, 709.4d) is never offered — Turn // Burn casts as no combined object", () => {
    // The engine does not offer fuse (fuseSplitCard.test.js). Were a combined split card on the stack, it would be a fused split spell,
    // which has its two halves' combined characteristics (CR 709.4d, 702.102b): spellOnStack.counterColorsOf reads the card's own
    // colours (faceUp.characteristicColors — a split card is no double-faced card), so it is blue and red, a legal Gainsay target.
    // (Until 2026-10-18 the read took any " // " card's front face off `card_faces` and failed closed without them.)
    const offers = castsOf(board({ active: "user", user: { hand: [H("tb", TURN_BURN)], pool: { U: 2, R: 2, C: 4 } } }), "user", "tb");
    expect(offers.filter((a) => !a.faceCard)).toEqual([]);
    expect(spellMatchesCounterFilter({ kind: "spell", source: H("tb", TURN_BURN) }, "any", { colorFilter: { color: "U" } })).toBe(true);
  });
});

// ─── the cast watchers ──────────────────────────────────────────────────────────
describe("\"whenever a player casts a red spell\" reads the half on the stack — Kor Firewalker", () => {
  // (The AI's own Grizzly Bears gives Ice a target either way, so the offer never hangs on Kor Firewalker's protection.)
  const withFirewalker = (card, pool) => board({ user: { battlefield: [P("kf", KOR_FIREWALKER, "user")] }, ai: { hand: [card], pool, battlefield: [P("ab", BEARS, "ai")] } });

  it("⭐ Ice is not red: Kor Firewalker does not trigger", () => {
    const s = cast(withFirewalker(H("fi", FIRE_ICE), { U: 1, C: 1 }), "ai", "fi", named("Ice"));
    expect(spellNamed(s, "Ice")).toBeTruthy();
    expect(triggersFrom(s, "Kor Firewalker")).toHaveLength(0);
  });

  it("Fire is red: Kor Firewalker triggers", () => {
    const s = cast(withFirewalker(H("fi", FIRE_ICE), { R: 1, C: 1 }), "ai", "fi", named("Fire"));
    expect(triggersFrom(s, "Kor Firewalker")).toHaveLength(1);
  });

  it("⭐ Blow Off Steam is red: Kor Firewalker triggers — the blue Frolicking Familiar cast normally does not", () => {
    const steam = cast(withFirewalker(H("ff", FROLICKING_FAMILIAR), { R: 1 }), "ai", "ff", (a) => a.adventureCast);
    expect(spellNamed(steam, "Blow Off Steam")).toBeTruthy();
    expect(triggersFrom(steam, "Kor Firewalker")).toHaveLength(1);
    const familiar = cast(withFirewalker(H("ff", FROLICKING_FAMILIAR), { U: 1, C: 2 }), "ai", "ff", (a) => !a.adventureCast);
    expect(triggersFrom(familiar, "Kor Firewalker")).toHaveLength(0);
  });

  it("control: Lightning Bolt is red — Kor Firewalker triggers", () => {
    const s = cast(withFirewalker(H("lb", LIGHTNING_BOLT), { R: 1 }), "ai", "lb", targetsId("user"));
    expect(triggersFrom(s, "Kor Firewalker")).toHaveLength(1);
  });
});

// ─── protection from a colour ───────────────────────────────────────────────────
describe("protection from red (CR 702.16b) reads the half being cast — Kor Firewalker can't be the target of a red spell", () => {
  const atFirewalker = (card, pool) => board({ active: "user", user: { hand: [card], pool }, ai: { battlefield: [P("kf", KOR_FIREWALKER, "ai")] } });

  it("⭐ Ice (blue) may tap Kor Firewalker; Fire (red) may not aim at it", () => {
    const offers = castsOf(atFirewalker(H("fi", FIRE_ICE), { R: 1, U: 1, C: 1 }), "user", "fi");
    expect(offers.filter(named("Ice")).some(targetsId("kf"))).toBe(true);
    expect(offers.filter(named("Fire")).some(targetsId("kf"))).toBe(false);
    expect(offers.filter(named("Fire")).length).toBeGreaterThan(0); // Fire is still offered at other targets
  });

  it("⭐ Blow Off Steam (red) may not aim at Kor Firewalker; the blue Steam Clean may", () => {
    const steam = castsOf(atFirewalker(H("ff", FROLICKING_FAMILIAR), { R: 1 }), "user", "ff").filter((a) => a.adventureCast);
    expect(steam.length).toBeGreaterThan(0);
    expect(steam.some(targetsId("kf"))).toBe(false);
    const clean = castsOf(atFirewalker(H("sv", SCALDING_VIPER), { U: 1, C: 1 }), "user", "sv").filter((a) => a.adventureCast);
    expect(clean.some(targetsId("kf"))).toBe(true);
  });

  it("control: Lightning Bolt may not aim at Kor Firewalker", () => {
    const bolt = castsOf(atFirewalker(H("lb", LIGHTNING_BOLT), { R: 1 }), "user", "lb");
    expect(bolt.length).toBeGreaterThan(0);
    expect(bolt.some(targetsId("kf"))).toBe(false);
  });
});

// ─── the projected faces ────────────────────────────────────────────────────────
describe("the projected face carries the half's own colours (CR 202.2)", () => {
  it("each split half is the colour of its own mana symbols; a hybrid half is each of its colours (CR 202.2d)", () => {
    expect(splitFaceCards(FIRE_ICE).map((f) => [f.name, f.colors])).toEqual([["Fire", ["R"]], ["Ice", ["U"]]]);
    expect(splitFaceCards(RESPONSE_RESURGENCE).map((f) => [f.name, [...f.colors].sort()])).toEqual([["Response", ["R", "W"]], ["Resurgence", ["R", "W"]]]);
  });

  it("an Adventure is its own colour; the permanent half keeps the card's normal colour (CR 715.4)", () => {
    expect(adventureFaceCard(FROLICKING_FAMILIAR).colors).toEqual(["R"]);
    expect(adventureFaceCard(SCALDING_VIPER).colors).toEqual(["U"]);
    expect(permanentFaceCard(FROLICKING_FAMILIAR).colors).toEqual(["U"]);
    expect(permanentFaceCard(SCALDING_VIPER).colors).toEqual(["R"]);
  });
});
