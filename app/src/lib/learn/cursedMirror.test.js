/**
 * CURSED MIRROR — the play-weighted program, #448.
 *   "{T}: Add {R}.
 *    As this artifact enters, you may have it become a copy of any creature on the battlefield until end of turn, except it
 *    has haste."
 *
 * An "as [this permanent] enters" ability is a replacement effect (CR 614.1c): the copy is made AS it enters, so it enters as
 * that creature — the copied creature's enters triggers and "as this enters" abilities work (CR 707.5; the bundled rulings) — and
 * a creature that enters at the same time can't be chosen. The copy takes the creature's copiable values only (CR 707.2: no
 * counters, no Auras, no other effects), plus haste, which is part of the copy (CR 707.9a). "Until end of turn" ends in the
 * cleanup step (CR 514.2): it is Cursed Mirror again. While it is a copy it has no "{T}: Add {R}" (the bundled ruling); afterwards
 * it does. Something that copies it while it is a copy keeps being that creature with haste: the duration is not copied (the
 * bundled ruling).
 *
 * THE MODEL: the entering clone lane (cloneCopy.js, resolvers.resolveCloneChoice) — the permanent's card is the snapshot, the
 * Mirror rides as its printedCard — with the duration stamped on the permanent and swept at cleanup (gameState.
 * revertEndOfTurnCopies). The cast entry asks (the clone-search choice: a person picks or declines; an AI seat takes the house
 * policy); a put onto the battlefield takes the house policy for every seat (zones.enterCardFromZone).
 *
 * THE POLICY (cloneCopy.pickTemporaryCopy): copy the best body on the battlefield — any controller's — when it would attack
 * profitably (its controller's turn, combat still ahead: some opponent has no untapped creature that can block it, kill it and
 * live) or block profitably (another player's turn, before blocks: it can block a creature that threatens its controller and
 * live); otherwise decline and keep the mana rock.
 *
 * Real oracle fixtures (bundled Scryfall, the 2026-10-01 data, generated by cardIndex.publicCard — never typed by hand).
 */
