const P = (id, card, controller = "user", extra = {}) => ({ ...createPermanent({ id, card: { id: `c-${id}`, ...card }, controller, summoningSick: false }), ...extra });
const many = (n, card, controller, prefix) => Array.from({ length: n }, (_, i) => P(`${prefix}${i + 1}`, card, controller));
const H = (id, card) => ({ ...card, id });
const bears = (who) => [1, 2, 3].map((i) => H(`${who}-lib${i}`, BEARS));
function board({ user = [], ai = [], hand = [], aiHand = [], library, active = "user", phase = "precombat-main", step = "main" } = {}) {
  const g = createGameState({ userDeck: [], aiDeck: [] });
  return { ...g, turn: 5, activePlayer: active, priorityHolder: active, phase, step, stack: [], pendingTriggers: [], consecutivePasses: 0,
    players: { ...g.players,
      user: { ...g.players.user, battlefield: user, hand, library: library ?? bears("user"), landsPlayedThisTurn: 1 },
      ai: { ...g.players.ai, battlefield: ai, hand: aiHand, library: bears("ai"), landsPlayedThisTurn: 1 } } };
}
const castsOf = (s, who, cardId) => legalActionsForPlayer({ ...s, priorityHolder: who }, who).filter((a) => a.kind === "cast-spell" && a.cardId === cardId);
const castAndResolve = (s, cardId, who = "user", pick = (as) => as[0]) => resolveTopOfStack(dispatchAction({ ...s, priorityHolder: who }, pick(castsOf(s, who, cardId))));
const mirrorPerm = (s, who = "user") => s.players[who].battlefield.find((p) => (p.printedCard || p.card)?.name === "Cursed Mirror");
const view = (s, perm) => ({
  name: perm.card.name,
  printed: perm.printedCard?.name ?? null,
  creature: permanentIsCreature(s, perm.id),
  pt: permanentIsCreature(s, perm.id) ? [permanentPower(s, perm.id), permanentToughness(s, perm.id)] : null,
  haste: permanentHasKeyword(s, perm.id, "Haste"),
  tapsForR: !!manaProduction(perm.card)?.colors?.includes("R"),
});
const attackersFor = (s, who) => legalActionsForPlayer({ ...s, priorityHolder: who }, who).filter((a) => a.kind === "declare-attacker").map((a) => a.permanentId);
function stepTo(s, phase, step) {
  for (let i = 0; i < 40 && !(s.phase === phase && s.step === step); i++) s = nextStep(s);
  if (!(s.phase === phase && s.step === step)) throw new Error(`never reached ${phase}/${step}`);
  return s;
}
