/**
 * REPRIEVE — the play-weighted program, #603 (EDHREC #603).
 *   "Return target spell to its owner's hand.
 *    Draw a card."
 *
 * THE PARSE: "return target spell to its owner's hand" → { op: "bounce-spell-or-permanent", targetType: "spell", notCounter:
 * true } — Hullbreaker Horror's stack half with no controller scope (any spell, the caster's own included), then the plain draw.
 * The pool is the stack's SPELLS only, copies included (CR 112.1a) — an ability is never a target (CR 113.9: abilities on the
 * stack aren't spells; the enumerator reads `kind: "spell"`). Returning a spell is not countering it (CR 701.6a), so a spell
 * that can't be countered is still a legal target, and the target spell's controller gets nothing back (no refund, none of
 * its effects).
 *
 * THE STACK-LEAVE PRIMITIVE (atoms/stack.counterSpellById — every counter, Remand, Memory Lapse, Venser and this bounce
 * take it), brought to the rules a bounce exercises:
 *  - The card goes to its OWNER's hand (CR 400.3): Ragavan's caster plays the opponent's card, and it goes home.
 *  - The WHOLE card moves: a split half (CR 709.4), a modal DFC face (CR 712.8a), an adventurer's face (CR 715.4) and a
 *    flashback cast's cost view rode the stack as projections; the card taken out of its zone is what leaves.
 *  - A COPY of a spell ceases to exist outside the stack (CR 704.5e, 707.10a) — returned, countered or exiled, it reaches no
 *    zone and enters no graveyard.
 *  - FLASHBACK (CR 702.34a): "exile this card instead of putting it anywhere else any time it would leave the stack" — the
 *    exile beats the hand (and Remand's hand, Memory Lapse's library).
 * And at the cast (actionDispatcher, beside the impulse stamps): CR 400.7 — an adventurer creature cast out of adventure exile
 * leaves that stay's permission behind, so neither a return to hand nor a death brings back a card castable from exile.
 *
 * THE ILLEGAL TARGET (CR 608.2b): with its one target gone Reprieve doesn't resolve — no draw. And the same rule for an
 * Adventure, which the arm also reaches (Take It Back): a fizzled Adventure never resolved, so CR 715.3d's exile doesn't
 * apply — it goes to its owner's graveyard and the creature is not castable from exile (resolvers.js EFFECT_PROGRAM). A copy of
 * an Adventure (CR 715.3c) is no card, so it goes on no adventure either (stack.spellCopyPayload).
 *
 * The arm completes two more cards, each witnessed here: Bilbo's Gambit (the gift is never promised — the engine's gift policy,
 * castModifiers.stripGiftPromise — so its base mode is the whole card) and Spellscorn Coven // Take It Back. Failure // Comply
 * stays parked on Comply; Unsubstantiate ("spell or creature") and Obscura Interceptor ("up to one target spell", reflexive)
 * stay parked on their own wording.
 *
 * Unmodeled, and accepted as a safe under-offer: CR 903.9b lets a commander's owner put it into the command zone instead of a
 * hand; the engine (every bounce, Venser and Remand included) leaves it in the hand, which is a legal outcome of that choice.
 *
 * Real oracle fixtures (bundled Scryfall, the 2026-10-01 data, generated by cardIndex.publicCard — never typed by hand).
 */
