const H = (id, card) => ({ ...card, id });
const P = (id, card, controller) => createPermanent({ id, card: { ...card, id: `c-${id}` }, controller, summoningSick: false });
/** A two-seat table in `active`'s precombat main; each seat's hand / graveyard / battlefield / pool given, three Bears in
 *  each library (so a draw is visible). */
function board({ active = "user", user = {}, ai = {} } = {}) {
  const g = createGameState({ userDeck: [], aiDeck: [] });
  const lib = (who) => [1, 2, 3].map((i) => ({ ...BEARS, id: `${who}-lib${i}` }));
  const seat = (who, o) => ({ ...g.players[who], battlefield: o.battlefield || [], hand: o.hand || [], graveyard: o.graveyard || [], exile: o.exile || [],
    manaPool: { ...g.players[who].manaPool, ...(o.pool || {}) }, library: o.library || lib(who) });
  return { ...g, turn: 5, activePlayer: active, priorityHolder: active, phase: "precombat-main", step: "main", stack: [], pendingTriggers: [], consecutivePasses: 0,
    players: { ...g.players, user: seat("user", user), ai: seat("ai", ai) } };
}
const castsOf = (s, who, cardId) => legalActionsForPlayer({ ...s, priorityHolder: who }, who).filter((a) => a.kind === "cast-spell" && a.cardId === cardId);
/** Dispatch `who`'s one offered cast of `cardId` that `pick` accepts (the cast must be offered — the test fails otherwise). */
function cast(s, who, cardId, pick = () => true) {
  const a = castsOf(s, who, cardId).find(pick);
  expect(a, `${who} is offered a cast of ${cardId}`).toBeTruthy();
  return dispatchAction({ ...s, priorityHolder: who }, a);
}
const aimedAt = (name) => (a) => (a.targets || []).some((t) => t.name === name);
const names = (cards) => cards.map((c) => c.name);
const zonesOf = (s, who) => ({ hand: names(s.players[who].hand), graveyard: names(s.players[who].graveyard), exile: names(s.players[who].exile) });
const stackNames = (s) => s.stack.map((o) => o.source?.name);
const errors = (s) => (s.log || []).filter((e) => e.kind === "stack-resolve-error");
/** Every card object named `name` anywhere in the game: each seat's zones, the battlefield's cards, the stack's sources. */
function everywhere(s, name) {
  const out = [];
  for (const [pid, p] of Object.entries(s.players)) {
    for (const z of ["hand", "graveyard", "exile", "library"]) for (const c of p[z] || []) if (c.name === name) out.push(`${pid}.${z}`);
    for (const perm of p.battlefield || []) if (perm.card?.name === name) out.push(`${pid}.battlefield`);
  }
  for (const o of s.stack) if (o.source?.name === name) out.push(o.isCopy ? "stack(copy)" : "stack");
  return out.sort();
}
/** The opponent (ai) casts `spell` (card id "sp" — the offered cast `pick` accepts) in their own main phase; the user holds
 *  Reprieve and {W}{1}. */
function theirSpellOnStack(spell, { pick = () => true, userExtra = {}, aiExtra = {} } = {}) {
  const s0 = board({ active: "ai",
    user: { hand: [H("rep", REPRIEVE)], pool: { W: 1, C: 1 }, ...userExtra },
    ai: { hand: [H("sp", spell)], pool: { U: 6, W: 2, R: 2, G: 3, C: 2 }, ...aiExtra } });
  return cast(s0, "ai", "sp", pick);
}

