/**
 * MOX DIAMOND — the play-weighted program, #247.
 *   "If this artifact would enter, you may discard a land card instead. If you do, put this artifact onto the battlefield.
 *    If you don't, put it into its owner's graveyard.
 *    {T}: Add one mana of any color."
 *
 * A replacement effect (CR 614.1a — "instead") on the event of it entering, applied as it would enter (CR 113.6h, 614.12): the
 * choice is made before it enters (CR 614.12a), and the discard is another object changing zones as part of it (CR 614.13).
 * Putting it onto the battlefield after the discard is not replaced again (CR 614.5). Declined — or with no land card to
 * discard — it never enters: no enters trigger, never a mana source (the bundled ruling), and the card goes to its owner's
 * graveyard (a token there ceases to exist).
 *
 * It applies wherever it would enter (discardLandToEnter.js, read at every entry): the resolving spell (resolvers.enterPermanent
 * — a clone entering as a copy of it too, CR 707.5), every put onto the battlefield (zones.enterCardFromZone — a search, a return
 * from the graveyard, a mass return, a put from the hand) and a token created as a copy.
 *
 * THE CHOICE is the house policy for every seat, as every other entry replacement decides (the shockland inside an effect, the
 * chosen type / colour / card type, riot, Fabricate, tribute): discard only with a land card in hand and either the land drop
 * already made this turn or two or more land cards held; the land discarded is a basic first. A person's seat is not asked —
 * a documented limit (discardLandToEnter.js). The AI holds the cast when the policy would decline (opponentAI, `discardEnterHold`).
 *
 * Real oracle fixtures (bundled Scryfall, the 2026-10-01 data, generated by cardIndex.publicCard — never typed by hand).
 */
