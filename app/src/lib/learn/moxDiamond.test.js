// ─── harness ──────────────────────────────────────────────────────────────────
const P = (id, card, controller = "user", extra = {}) => ({ ...createPermanent({ id, card: { id: `c-${id}`, ...card }, controller, summoningSick: false }), ...extra });
const many = (n, card, controller, prefix) => Array.from({ length: n }, (_, i) => P(`${prefix}${i + 1}`, card, controller));
const H = (id, card) => ({ ...card, id });
const bears = (who) => [1, 2, 3].map((i) => H(`${who}-lib${i}`, GRIZZLY_BEARS));
function board({ user = [], ai = [], hand = [], aiHand = [], library, graveyard = [], landsPlayed = 1, aiLandsPlayed = 0, active = "user", humanSeats } = {}) {
  const g = createGameState({ userDeck: [], aiDeck: [] });
  return { ...g, turn: 5, activePlayer: active, priorityHolder: active, phase: "precombat-main", step: "main", stack: [], pendingTriggers: [], consecutivePasses: 0,
    ...(humanSeats ? { humanSeats } : {}),
    players: { ...g.players,
      user: { ...g.players.user, battlefield: user, hand, graveyard, library: library ?? bears("user"), landsPlayedThisTurn: landsPlayed },
      ai: { ...g.players.ai, battlefield: ai, hand: aiHand, library: bears("ai"), landsPlayedThisTurn: aiLandsPlayed } } };
}
const castsOf = (s, who, cardId) => legalActionsForPlayer({ ...s, priorityHolder: who }, who).filter((a) => a.kind === "cast-spell" && a.cardId === cardId);
const castAndResolve = (s, cardId, pick = (as) => as[0]) => resolveTopOfStack(dispatchAction(s, pick(castsOf(s, "user", cardId))));
const names = (zone) => zone.map((c) => c.name).sort();
const moxesOn = (s, who = "user") => s.players[who].battlefield.filter((p) => p.card?.name === "Mox Diamond").map((p) => ({ token: !!p.card.token }));
const decisions = (s) => (s.log || []).filter((e) => e.kind === "enter-discard-replacement").map((e) => ({ controller: e.controller, discarded: e.discarded, auto: e.auto }));
const row = (s, who = "user") => ({ moxes: moxesOn(s, who), hand: names(s.players[who].hand), graveyard: names(s.players[who].graveyard) });

describe("⭐ WITNESS — cast: it enters only by discarding a land card", () => {
  it("⭐ with a land in hand (the land drop made): the Forest is discarded and the Mox enters", () => {
    const s = castAndResolve(board({ hand: [H("mox", MOX), H("f", FOREST)] }), "mox");
    const r = { ...row(s), decisions: decisions(s) };
    console.log("  WITNESS mox-cast", JSON.stringify(r));
    expect(r).toEqual({ moxes: [{ token: false }], hand: [], graveyard: ["Forest"], decisions: [{ controller: "user", discarded: "Forest", auto: true }] });
  });

  it("⭐ with no land card in hand: it never enters — the Mox goes to its owner's graveyard, the Bolt stays in hand", () => {
    const s = castAndResolve(board({ hand: [H("mox", MOX), H("bolt", LIGHTNING_BOLT)] }), "mox");
    const r = { ...row(s), decisions: decisions(s), entered: (s.log || []).some((e) => e.kind === "permanent-enters" && e.cardName === "Mox Diamond") };
    console.log("  WITNESS mox-noland", JSON.stringify(r));
    expect(r).toEqual({ moxes: [], hand: ["Lightning Bolt"], graveyard: ["Mox Diamond"], decisions: [{ controller: "user", discarded: null, auto: true }], entered: false });
  });

  it("the discard is a discard (CR 701.9a): Glint-Horn Buccaneer's watcher triggers and the opponent takes 1", () => {
    const s0 = board({ user: [P("gh", GLINT_HORN)], hand: [H("mox", MOX), H("f", FOREST)] });
    const s = finalizeStackResolution(castAndResolve(s0, "mox"));
    const trigger = (s.stack || []).find((o) => o.kind === "triggered-ability");
    const after = trigger ? resolveTopOfStack(s) : s;
    expect({ trigger: trigger?.source?.name ?? null, aiLife: after.players.ai.life }).toEqual({ trigger: "Glint-Horn Buccaneer", aiLife: s0.players.ai.life - 1 });
  });
});

describe("THE POLICY — conservative, the same for every seat", () => {
  it("one land card and the land drop not yet made: it keeps the land — the Mox goes to the graveyard", () => {
    const s = castAndResolve(board({ hand: [H("mox", MOX), H("f", FOREST)], landsPlayed: 0 }), "mox");
    expect(row(s)).toEqual({ moxes: [], hand: ["Forest"], graveyard: ["Mox Diamond"] });
  });

  it("two land cards and the land drop not yet made: it discards one — the basic, keeping the Breeding Pool", () => {
    const s = castAndResolve(board({ hand: [H("mox", MOX), H("bp", BREEDING_POOL), H("f", FOREST)], landsPlayed: 0 }), "mox");
    expect(row(s)).toEqual({ moxes: [{ token: false }], hand: ["Breeding Pool"], graveyard: ["Forest"] });
  });

  it("a modal DFC whose back face is a land is not a land card in the hand (CR 712.8a — its front face only)", () => {
    const s = castAndResolve(board({ hand: [H("mox", MOX), H("va", VALAKUT_AWAKENING)] }), "mox");
    expect(row(s)).toEqual({ moxes: [], hand: ["Valakut Awakening // Valakut Stoneforge"], graveyard: ["Mox Diamond"] });
  });

  it("a person's seat takes the same policy, logged as an automatic decision (the documented limit)", () => {
    const s = castAndResolve(board({ hand: [H("mox", MOX), H("f", FOREST)], humanSeats: ["user"] }), "mox");
    expect({ ...row(s), decisions: decisions(s), pending: s.pendingChoice ?? null })
      .toEqual({ moxes: [{ token: false }], hand: [], graveyard: ["Forest"], decisions: [{ controller: "user", discarded: "Forest", auto: true }], pending: null });
  });
});

describe("⭐ put onto the battlefield by an effect — it asks there too", () => {
  it("⭐ searched (Whir of Invention, X=1) with a Forest in hand: the Forest is discarded and the Mox enters", () => {
    const s0 = board({ user: many(4, ISLAND, "user", "is"), hand: [H("whir", WHIR), H("f", FOREST)], library: [H("mox", MOX), H("b1", GRIZZLY_BEARS)] });
    let s = castAndResolve(s0, "whir", (as) => as.find((a) => a.xValue === 1));
    s = resolveTutorChoice(s, "mox");
    expect(row(s)).toEqual({ moxes: [{ token: false }], hand: [], graveyard: ["Forest", "Whir of Invention"] });
  });

  it("⭐ searched with no land card in hand: the Mox goes from the library to its owner's graveyard", () => {
    const s0 = board({ user: many(4, ISLAND, "user", "is"), hand: [H("whir", WHIR), H("bolt", LIGHTNING_BOLT)], library: [H("mox", MOX), H("b1", GRIZZLY_BEARS)] });
    let s = castAndResolve(s0, "whir", (as) => as.find((a) => a.xValue === 1));
    s = resolveTutorChoice(s, "mox");
    expect({ ...row(s), library: names(s.players.user.library) })
      .toEqual({ moxes: [], hand: ["Lightning Bolt"], graveyard: ["Mox Diamond", "Whir of Invention"], library: ["Grizzly Bears"] });
  });

  it("the control: Manalith searched the same way enters without discarding anything", () => {
    const s0 = board({ user: many(6, ISLAND, "user", "is"), hand: [H("whir", WHIR), H("f", FOREST)], library: [H("ml", MANALITH), H("b1", GRIZZLY_BEARS)] });
    let s = castAndResolve(s0, "whir", (as) => as.find((a) => a.xValue === 3));
    s = resolveTutorChoice(s, "ml");
    expect({ manalith: s.players.user.battlefield.some((p) => p.card?.name === "Manalith"), hand: names(s.players.user.hand), decisions: decisions(s) })
      .toEqual({ manalith: true, hand: ["Forest"], decisions: [] });
  });

  it("returned from the graveyard (Argivian Restoration): with a land it enters; without one it stays in the graveyard", () => {
    const withLand = castAndResolve(board({ user: many(4, ISLAND, "user", "is"), hand: [H("ar", ARGIVIAN_RESTORATION), H("f", FOREST)], graveyard: [H("mox", MOX)] }),
      "ar", (as) => as.find((a) => a.targets?.some((t) => t.id === "mox")));
    const without = castAndResolve(board({ user: many(4, ISLAND, "user", "is"), hand: [H("ar", ARGIVIAN_RESTORATION), H("bolt", LIGHTNING_BOLT)], graveyard: [H("mox", MOX)] }),
      "ar", (as) => as.find((a) => a.targets?.some((t) => t.id === "mox")));
    expect({ withLand: row(withLand), without: row(without) }).toEqual({
      withLand: { moxes: [{ token: false }], hand: [], graveyard: ["Argivian Restoration", "Forest"] },
      without: { moxes: [], hand: ["Lightning Bolt"], graveyard: ["Argivian Restoration", "Mox Diamond"] },
    });
  });

  it("⭐ one event, two Moxes, one land (Brilliant Restoration): one Mox enters on the one land — the same card can't be discarded twice (CR 614.13b)", () => {
    const s0 = board({ user: many(7, PLAINS, "user", "pl"), hand: [H("br", BRILLIANT_RESTORATION), H("f", FOREST)], graveyard: [H("mox1", MOX), H("mox2", MOX)] });
    const s = castAndResolve(s0, "br");
    expect({ ...row(s), decisions: decisions(s).map((d) => d.discarded) })
      .toEqual({ moxes: [{ token: false }], hand: [], graveyard: ["Brilliant Restoration", "Forest", "Mox Diamond"], decisions: ["Forest", null] });
  });
});

describe("⭐ copies — a clone entering as a copy, and a token copy (CR 707.5)", () => {
  it("Sculpting Steel copying a Mox Diamond: with a land it enters as the copy; without one the Steel goes to the graveyard", () => {
    const go = (hand) => {
      const s0 = board({ user: [P("mox", MOX), ...many(3, ISLAND, "user", "is")], hand });
      const s = resolveTopOfStack(dispatchAction(s0, castsOf(s0, "user", "ss")[0]));
      return finalizeStackResolution(resolveCloneChoice(s, "mox"));
    };
    const withLand = go([H("ss", SCULPTING_STEEL), H("f", FOREST)]);
    const without = go([H("ss", SCULPTING_STEEL), H("bolt", LIGHTNING_BOLT)]);
    expect({ withLand: row(withLand), without: row(without) }).toEqual({
      withLand: { moxes: [{ token: false }, { token: false }], hand: [], graveyard: ["Forest"] },
      without: { moxes: [{ token: false }], hand: ["Lightning Bolt"], graveyard: ["Sculpting Steel"] },
    });
  });

  it("Flash Photography on a Mox Diamond: with a land the token is created; without one no token is", () => {
    const go = (hand) => castAndResolve(board({ user: [P("mox", MOX), ...many(4, ISLAND, "user", "is")], hand }), "fp", (as) => as.find((a) => a.targets?.some((t) => t.id === "mox")));
    const withLand = go([H("fp", FLASH_PHOTOGRAPHY), H("f", FOREST)]);
    const without = go([H("fp", FLASH_PHOTOGRAPHY), H("bolt", LIGHTNING_BOLT)]);
    expect({ withLand: row(withLand), without: row(without) }).toEqual({
      withLand: { moxes: [{ token: false }, { token: true }], hand: [], graveyard: ["Flash Photography", "Forest"] },
      without: { moxes: [{ token: false }], hand: ["Lightning Bolt"], graveyard: ["Flash Photography"] },
    });
  });

  it("Second Harvest copying a Mox Diamond token: with a land the second token is created; without one it is not", () => {
    const moxToken = P("tmox", { ...MOX, token: true });
    const go = (hand) => castAndResolve(board({ user: [moxToken, ...many(4, FOREST, "user", "fo")], hand }), "sh");
    const withLand = go([H("sh", SECOND_HARVEST), H("f", FOREST)]);
    const without = go([H("sh", SECOND_HARVEST), H("bolt", LIGHTNING_BOLT)]);
    expect({ withLand: row(withLand), without: row(without) }).toEqual({
      withLand: { moxes: [{ token: true }, { token: true }], hand: [], graveyard: ["Forest", "Second Harvest"] },
      without: { moxes: [{ token: true }], hand: ["Lightning Bolt"], graveyard: ["Second Harvest"] },
    });
  });
});

describe("the AI casts it only when the policy would discard", () => {
  const aiBoard = (aiHand, aiLandsPlayed) => board({ active: "ai", aiHand, aiLandsPlayed, ai: [], landsPlayed: 0 });
  const aiPick = (s) => pickAction(s, "ai", legalActionsForPlayer(s, "ai"), { archetype: "midrange" });

  it("⭐ no land card in hand: it holds the Mox (casting it would only bin it)", () => {
    const pick = aiPick(aiBoard([H("amox", MOX)], 1));
    expect({ kind: pick?.kind ?? null, cardId: pick?.cardId ?? null }).toEqual({ kind: "pass-priority", cardId: null });
  });

  it("the land drop made and a land in hand: it casts the Mox", () => {
    const pick = aiPick(aiBoard([H("amox", MOX), H("af", FOREST)], 1));
    expect({ kind: pick?.kind, cardId: pick?.cardId }).toEqual({ kind: "cast-spell", cardId: "amox" });
  });

  it("the held cast is only a ranking: the cast stays offered (THE CREED — the engine decides what is legal)", () => {
    const s = aiBoard([H("amox", MOX)], 1);
    expect(castsOf(s, "ai", "amox").length).toBeGreaterThan(0);
  });
});

describe("the recognizer and the policy reader", () => {
  it("reads Mox Diamond's printed sentence whole — a different cost or a missing rider is not it", () => {
    expect(entersByDiscardingLand(MOX)).toBe(true);
    expect(entersByDiscardingLand({ oracle: "If this artifact would enter, you may discard a card instead. If you do, put this artifact onto the battlefield. If you don't, put it into its owner's graveyard." })).toBe(false);
    expect(entersByDiscardingLand({ oracle: "If this artifact would enter, you may discard a land card instead. If you do, put this artifact onto the battlefield." })).toBe(false);
    expect(entersByDiscardingLand(MANALITH)).toBe(false);
  });

  it("pickEnterDiscardLand names the land the policy would discard, or null", () => {
    expect(pickEnterDiscardLand(board({ hand: [H("mox", MOX), H("bp", BREEDING_POOL), H("f", FOREST)], landsPlayed: 0 }), "user")).toBe("f");
    expect(pickEnterDiscardLand(board({ hand: [H("mox", MOX), H("f", FOREST)], landsPlayed: 0 }), "user")).toBe(null);
    expect(pickEnterDiscardLand(board({ hand: [H("mox", MOX), H("bp", BREEDING_POOL)], landsPlayed: 1 }), "user")).toBe("bp");
    expect(pickEnterDiscardLand(board({ hand: [H("mox", MOX), H("bolt", LIGHTNING_BOLT)] }), "user")).toBe(null);
  });
});

