// ─── harness ──────────────────────────────────────────────────────────────────
const P = (id, card, controller = "user", extra = {}) => ({ ...createPermanent({ id, card: { id: `c-${id}`, ...card }, controller, summoningSick: false }), ...extra });
const H = (id, card) => ({ ...card, id });
function board({ user = [], ai = [], hand = [], aiHand = [], pool = {}, aiPool = {}, active = "user" } = {}) {
  const g = createGameState({ userDeck: [], aiDeck: [] });
  return { ...g, turn: 5, activePlayer: active, priorityHolder: active, phase: "precombat-main", step: "main", stack: [], pendingTriggers: [], consecutivePasses: 0,
    players: { ...g.players,
      user: { ...g.players.user, battlefield: user, hand, manaPool: { ...g.players.user.manaPool, ...pool } },
      ai: { ...g.players.ai, battlefield: ai, hand: aiHand, manaPool: { ...g.players.ai.manaPool, ...aiPool } } } };
}
const cast = (s, cardId, who = "user") => {
  const offer = legalActionsForPlayer(s, who).find((a) => a.kind === "cast-spell" && a.cardId === cardId);
  expect(offer).toBeTruthy();
  return dispatchAction(s, offer);
};
const ids = (s, who) => s.players[who].battlefield.map((p) => p.id).sort();
const names = (cards) => cards.map((c) => c.name).sort();
const pt = (s, id) => `${permanentPower(s, id)}/${permanentToughness(s, id)}`;
const errors = (s) => (s.log || []).filter((e) => e.kind === "stack-resolve-error");
const aiPick = (s) => pickAction(s, "ai", legalActionsForPlayer(s, "ai"), { archetype: "midrange" });

describe("the cards and their parse", () => {
  it("⭐ classify: Raise the Palisade and Crippling Fear native-spell; the chosen-type neighbours this slice must not touch stay where they were", () => {
    const row = Object.fromEntries(Object.entries({ RAISE, CRIPPLING, KINDRED_DOMINANCE, HARSH_MERCY, EXTINCTION }).map(([k, c]) => [k, classifyCard(c)]));
    expect(row).toEqual({ RAISE: "native-spell", CRIPPLING: "native-spell", KINDRED_DOMINANCE: "native-spell", HARSH_MERCY: "arbiter-spell", EXTINCTION: "arbiter-spell" });
  });

  it("each parses HIGH with no chosen target and no X; the AI holds both as creature wipes (they unlock only when it is clearly behind)", () => {
    const row = (c) => { const p = parseEffectProgram(c); return { conf: programConfidence(p), xSpell: p.xSpell, held: programContainsMassRemoval(p), creatureWipe: programContainsCreatureMassRemoval(p), targets: p.atoms.map((a) => a.targetType ?? null) }; };
    expect({ raise: row(RAISE), crippling: row(CRIPPLING) }).toEqual({
      raise: { conf: "high", xSpell: false, held: true, creatureWipe: true, targets: [null] },
      crippling: { conf: "high", xSpell: false, held: true, creatureWipe: true, targets: [null] },
    });
  });

  it("CONTROL — near misses stay unparsed: either sentence alone, another chooser, the creatures OF the type, a positive bonus, a rider", () => {
    const atoms = (clause) => parseEffectClause(clause, "Sorcery")?.atoms ?? [];
    expect({
      bounceOnly: atoms("Return all creatures that aren't of the chosen type to their owners' hands."),
      shrinkOnly: atoms("Creatures that aren't of the chosen type get -3/-3 until end of turn."),
      eachPlayer: atoms("Each player chooses a creature type. Return all creatures that aren't of a type chosen this way to their owners' hands."),
      ofTheType: atoms("Choose a creature type. Return all creatures of the chosen type to their owners' hands."),
      ofTheTypeShrink: atoms("Choose a creature type. Creatures of the chosen type get -3/-3 until end of turn."),
      bonus: atoms("Choose a creature type. Creatures that aren't of the chosen type get +2/+2 until end of turn."),
      riderAfter: atoms("Choose a creature type. Creatures that aren't of the chosen type get -3/-3 until end of turn. You gain 2 life."),
    }).toEqual({ bounceOnly: [], shrinkOnly: [], eachPlayer: [], ofTheType: [], ofTheTypeShrink: [], bonus: [], riderAfter: [] });
  });
});

describe("⭐ Raise the Palisade — cast, resolved", () => {
  it("⭐ the caster's Elves stay; every other creature goes to its OWNER's hand (a stolen creature goes home, a token ceases to exist); a changeling stays", () => {
    // user: two Elves, a Bear, a changeling, and the ai's Hill Giant (stolen — owner ai). ai: a Zombie, a Serra Angel and a Zombie token.
    const s0 = board({ hand: [H("raise", RAISE)], pool: { U: 5 },
      user: [P("llanowar", LLANOWAR_ELVES), P("fyndhorn", FYNDHORN_ELVES), P("bears", GRIZZLY_BEARS), P("auto", UNIVERSAL_AUTOMATON), P("giant", HILL_GIANT, "user", { owner: "ai" })],
      ai: [P("corpse", WALKING_CORPSE, "ai"), P("angel", SERRA_ANGEL, "ai"), P("ztok", { ...WALKING_CORPSE, name: "Zombie", token: true }, "ai")] });
    const onStack = cast(s0, "raise");
    const s = resolveTopOfStack(onStack);
    const row = { castTargets: onStack.stack[0].payload.params.targets, user: ids(s, "user"), ai: ids(s, "ai"), userHand: names(s.players.user.hand), aiHand: names(s.players.ai.hand),
      userGraveyard: names(s.players.user.graveyard), stack: s.stack.length, errors: errors(s).length };
    expect(row).toEqual({ castTargets: [], user: ["auto", "fyndhorn", "llanowar"], ai: [], userHand: ["Grizzly Bears"], aiHand: ["Hill Giant", "Serra Angel", "Walking Corpse"],
      userGraveyard: ["Raise the Palisade"], stack: 0, errors: 0 });
  });

  it("the type that spares the opponents more than the caster is never chosen: their two Zombies against the caster's one Zombie — the caster's Elf is chosen", () => {
    const s = resolveTopOfStack(cast(board({ hand: [H("raise", RAISE)], pool: { U: 5 },
      user: [P("llanowar", LLANOWAR_ELVES), P("corpse1", WALKING_CORPSE)], ai: [P("corpse2", WALKING_CORPSE, "ai"), P("corpse3", WALKING_CORPSE, "ai")] }), "raise"));
    expect({ user: ids(s, "user"), ai: ids(s, "ai"), userHand: names(s.players.user.hand), aiHand: names(s.players.ai.hand) })
      .toEqual({ user: ["llanowar"], ai: [], userHand: ["Walking Corpse"], aiHand: ["Walking Corpse", "Walking Corpse"] });
  });
});

describe("⭐ Crippling Fear — cast, resolved", () => {
  it("⭐ -3/-3 on every creature not of the chosen type: the Dreadmaw shrinks, the Giant and the indestructible Myr die; the caster's Elves are untouched", () => {
    const s0 = board({ hand: [H("fear", CRIPPLING)], pool: { B: 4 },
      user: [P("arch", ELVISH_ARCHDRUID), P("llanowar", LLANOWAR_ELVES)],
      ai: [P("maw", COLOSSAL_DREADMAW, "ai"), P("giant", HILL_GIANT, "ai"), P("myr", DARKSTEEL_MYR, "ai")] });
    const s = resolveTopOfStack(cast(s0, "fear"));
    const row = { user: ids(s, "user"), ai: ids(s, "ai"), arch: pt(s, "arch"), llanowar: pt(s, "llanowar"), maw: pt(s, "maw"), aiGraveyard: names(s.players.ai.graveyard), errors: errors(s).length };
    expect(row).toEqual({ user: ["arch", "llanowar"], ai: ["maw"], arch: "2/2", llanowar: "2/2", maw: "3/3", aiGraveyard: ["Darksteel Myr", "Hill Giant"], errors: 0 });
  });

  it("the set is fixed as it resolves: a creature that enters afterwards is not shrunk (the card's ruling), and a changeling is never in it", () => {
    const s0 = board({ hand: [H("fear", CRIPPLING)], pool: { B: 4 }, user: [P("llanowar", LLANOWAR_ELVES)], ai: [P("maw", COLOSSAL_DREADMAW, "ai"), P("auto", UNIVERSAL_AUTOMATON, "ai")] });
    const s1 = resolveTopOfStack(cast(s0, "fear"));
    const late = P("maw2", COLOSSAL_DREADMAW, "ai");
    const s2 = { ...s1, players: { ...s1.players, ai: { ...s1.players.ai, battlefield: [...s1.players.ai.battlefield, late] } } };
    expect({ maw: pt(s2, "maw"), late: pt(s2, "maw2"), auto: pt(s2, "auto") }).toEqual({ maw: "3/3", late: "6/6", auto: "1/1" });
  });
});

describe("⭐ the AI", () => {
  it("holds Crippling Fear and Raise the Palisade on an even board, and casts Crippling Fear when clearly behind — sparing its own Elves", () => {
    const even = board({ active: "ai", aiHand: [H("fear", CRIPPLING)], aiPool: { B: 4 }, ai: [P("arch", ELVISH_ARCHDRUID, "ai")], user: [P("bears", GRIZZLY_BEARS)] });
    const evenRaise = board({ active: "ai", aiHand: [H("raise", RAISE)], aiPool: { U: 5 }, ai: [P("arch", ELVISH_ARCHDRUID, "ai")], user: [P("bears", GRIZZLY_BEARS)] });
    const behind = board({ active: "ai", aiHand: [H("fear", CRIPPLING)], aiPool: { B: 4 }, ai: [P("arch", ELVISH_ARCHDRUID, "ai"), P("llanowar", LLANOWAR_ELVES, "ai")],
      user: [P("b1", GRIZZLY_BEARS), P("b2", GRIZZLY_BEARS), P("g1", HILL_GIANT), P("g2", HILL_GIANT), P("g3", HILL_GIANT)] });
    const pickRow = (s) => { const a = aiPick(s); return a && a.kind === "cast-spell" ? a.cardId : null; };
    const behindPick = aiPick(behind);
    const after = behindPick?.kind === "cast-spell" ? resolveTopOfStack(dispatchAction(behind, behindPick)) : behind;
    expect({ even: pickRow(even), evenRaise: pickRow(evenRaise), behind: behindPick?.kind === "cast-spell" ? behindPick.cardId : null, ai: ids(after, "ai"), user: ids(after, "user") })
      .toEqual({ even: null, evenRaise: null, behind: "fear", ai: ["arch", "llanowar"], user: [] });
  });
});
