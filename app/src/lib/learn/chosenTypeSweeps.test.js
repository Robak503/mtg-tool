/**
 * THE CHOSEN-TYPE SWEEPS — Kindred Dominance's resolution-time creature-type choice, read with its two other verbs (the
 * play-weighted arbiter-spell slice, 2026-10-18):
 *
 *   Raise the Palisade (EDHREC #888) — "Choose a creature type. Return all creatures that aren't of the chosen type to their owners'
 *                                       hands."
 *   Crippling Fear (#2047)           — "Choose a creature type. Creatures that aren't of the chosen type get -3/-3 until end of turn."
 *
 * THE CHOICE is made as the spell resolves (CR 608.2d — Crippling Fear's ruling: "You choose the creature type as Crippling Fear
 * resolves") and is one existing creature type (CR 205.3e; both cards' rulings: "you must choose an existing creature type"). The
 * shared policy chooses for every seat, as for Kindred Dominance (choicePolicy.autoPickCreatureTypeToSpare — the caster's creatures
 * of the type minus everyone else's). THE SET is every creature on the battlefield as the spell resolves that is not of the chosen
 * type by its current types; a creature that is every creature type (Changeling, CR 702.73a) is always of it.
 *   - the bounce returns each to its OWNER's hand, one event (CR 400.3 — a stolen creature goes home; a token ceases to exist,
 *     CR 111.7 / 704.5d);
 *   - the -3/-3 lands on exactly that set until end of turn (Crippling Fear's ruling: it "affects only creatures that aren't of the
 *     chosen type that are on the battlefield as it resolves. It won't affect creatures that enter the battlefield later in the
 *     turn"), and a creature it brings to 0 toughness dies (CR 704.5f) — indestructible does not save it.
 *
 * Real oracle fixtures (bundled Scryfall data, generated by cardIndex.publicCard — never typed by hand).
 */
