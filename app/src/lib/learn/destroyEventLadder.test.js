/**
 * THE DESTROY EVENT — one simultaneous event, read from the board as it began (a fix slice).
 *
 * A destroy that names several permanents destroys them at once (CR 701.8a). Replacement effects watch for the event and apply
 * as it would happen (CR 614.1), so every replacement that existed as the destruction began applies to it — even one whose
 * source is destroyed in the same event. The engine used to walk the target list one permanent at a time against a board it
 * had already partly destroyed: an Aura or a lord processed before the creature it protected was gone by the time the creature
 * was asked, and a "die → exile instead" or "graveyard → exile instead" source processed first no longer redirected the rest.
 * What this file pins:
 *
 *  1. THE LADDER (spellEffects.applyDestroyEffect): each permanent's destruction replacement — indestructible (CR 702.12b), a
 *     shield counter (CR 122.1c), a regeneration shield (CR 701.19a; "can't be regenerated", CR 701.19c), umbra armor
 *     (CR 702.89a) — is decided against the board as the event began. The decision is one function, gameState's
 *     destructionReplacementFor, which the lethal-damage state-based action (CR 704.5g) reads too: there is no second copy.
 *     Culling Ritual's "destroyed this way" count reads it on the same board, so the count and the destroy agree.
 *  2. WHERE IT WENT: "dies" means put into a graveyard from the battlefield (CR 700.4). A permanent a replacement keeps out of
 *     the graveyard — shuffled into its owner's library (Progenitus), exiled (Misery's Shadow, Rest in Peace, Dauthi
 *     Voidwalker) — did not die, and no dies trigger, batch watcher or death tally may say it did. One look-back constructor
 *     (gameState.deathLookback) builds the entry every death site hands the dies triggers, its flags read off the same card the
 *     zone move reads (a face-down permanent's real card, CR 400.6).
 *  3. AS IT LAST EXISTED: a leaves-the-battlefield ability looks back in time (CR 603.10a), so the look-back is the permanent's
 *     layer-aware characteristics, not its printed card: a crewed Vehicle or an animated land destroyed or sacrificed died as a
 *     creature. The one-permanent edict's victim pool reads the permanent the same way.
 *  4. BLOOD MONEY prints no "can't be regenerated": regeneration saves a creature from it. Its op now takes the parser's rider
 *     stamp like every destroy, so a rider would be honoured (a clearly labelled synthetic witness below).
 *
 * Real oracle fixtures (bundled Scryfall, generated by cardIndex.publicCard — never typed by hand). Everything runs through the
 * engine's entry points: legalActionsForPlayer → dispatchAction → resolveTopOfStack (the lethal-damage state-based action
 * through destroyLethalCreatures, the function every damage site calls).
 */
