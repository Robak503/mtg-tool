const P = (id, card, controller = "user", extra = {}) => ({ ...createPermanent({ id, card: { id: `c-${id}`, ...card }, controller, summoningSick: false }), ...extra });
const H = (id, card) => ({ ...card, id });
function board({ user = [], ai = [], hand = [], pool = {}, aiLibrary = null, active = "user" } = {}) {
  const g = createGameState({ userDeck: [], aiDeck: [] });
  const lib = (who) => [1, 2, 3].map((i) => ({ ...BEARS, id: `${who}-lib${i}` }));
  return { ...g, turn: 5, activePlayer: active, priorityHolder: active, phase: "precombat-main", step: "main", stack: [], pendingTriggers: [], consecutivePasses: 0,
    players: { ...g.players,
      user: { ...g.players.user, battlefield: user, hand, manaPool: { ...g.players.user.manaPool, ...pool }, library: lib("user") },
      ai: { ...g.players.ai, battlefield: ai, hand: [], library: aiLibrary || lib("ai") } } };
}
const withPool = (s, who, pool) => ({ ...s, players: { ...s.players, [who]: { ...s.players[who], manaPool: { ...s.players[who].manaPool, ...pool } } } });
const attach = (s, auraId, hostId) => attachPermanent(s, { equipId: auraId, targetId: hostId });
const actionsOf = (s, who) => legalActionsForPlayer({ ...s, priorityHolder: who }, who);
const castsOf = (s, cardId) => actionsOf(s, "user").filter((a) => a.kind === "cast-spell" && a.cardId === cardId);
// Cast (the first offer, or the one `pick` chooses) and resolve it — the dies triggers it wakes are flushed onto the stack.
const cast = (s, cardId, pick = () => true) => resolveTopOfStack(dispatchAction({ ...s, priorityHolder: "user" }, castsOf(s, cardId).find(pick)));
// Activate a permanent's non-mana ability (the one `pick` chooses) for `who` and resolve it.
const activate = (s, permId, who = "user", pick = () => true) => {
  const a = actionsOf(s, who).find((x) => x.kind === "activate-ability" && x.permanentId === permId && !x.isManaAbility && pick(x));
  return resolveTopOfStack(dispatchAction({ ...s, priorityHolder: who }, a));
};
// Mutavault's "{1}: This land becomes a 2/2 creature …" through its own activation, paid from a {C} put in the pool.
const animate = (s, permId, who = "user") => activate(withPool(s, who, { C: 1 }), permId, who, (x) => x.cost?.generic === 1);
const crew = (s, vehicleId) => dispatchAction(s, actionsOf(s, "user").find((a) => a.kind === "crew-vehicle" && a.permanentId === vehicleId));
const perm = (s, id) => Object.values(s.players).flatMap((p) => p.battlefield).find((p) => p.id === id) || null;
const names = (zone) => zone.map((c) => c.name).sort();
const count = (zone, name) => zone.filter((c) => c.name === name).length;
const triggersOf = (s, name) => s.stack.filter((o) => o.source?.name === name).length;
const errors = (s) => (s.log || []).filter((e) => e.kind === "stack-resolve-error");
const died = (s) => ({ user: s.players.user.creaturesDiedThisTurn || 0, ai: s.players.ai.creaturesDiedThisTurn || 0 });

