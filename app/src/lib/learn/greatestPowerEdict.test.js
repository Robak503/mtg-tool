/**
 * THE GREATEST-POWER EDICT (the play-weighted arbiter-spell slice, 2026-10-18):
 *
 *   Crackling Doom (EDHREC #2125) — "Crackling Doom deals 2 damage to each opponent. Each opponent sacrifices a creature with the
 *                                    greatest power among creatures that player controls."
 *
 * The edict chain (removal.advanceSacrificeChain) narrowed to the sacrificer's creatures of the greatest power — the sibling of
 * Flare of Malice's greatest-mana-value pool. Its rulings (bundled): "each opponent, starting with the active player and proceeding
 * in turn order, chooses which creature they will sacrifice and then all creatures are sacrificed at the same time"; "If a player
 * controls two or more creatures tied for the greatest power among creatures they control, that player chooses one of them to
 * sacrifice"; "Crackling Doom doesn't target any player or creature"; "The sacrifice is not dependent on the damage being dealt."
 * Power is read as it is now, through the layers (an anthem counts). A sacrifice is not a destroy: indestructible doesn't keep a
 * creature (CR 701.21a, 702.12b).
 *
 * Real oracle fixtures (bundled Scryfall data, generated by cardIndex.publicCard — never typed by hand).
 */
import { beforeEach, describe, expect, it } from "vitest";
import { _resetIdsForTests, createGameState, createPermanent } from "./gameState.js";
import { legalActionsForPlayer } from "./legalChoices.js";
import { dispatchAction } from "./actionDispatcher.js";
import { resolveTopOfStack } from "./gameEngine.js";
import { classifyCard } from "./coverage.js";
import { parseEffectClause, parseEffectProgram, programConfidence } from "./effects/parser.js";
import { resolveSacrificeChoice } from "./effects/runProgram.js";
import { pickAction } from "./opponentAI.js";

beforeEach(() => _resetIdsForTests());

// ─── real card fixtures (generated from the bundled Scryfall data) ──────────────
const CRACKLING_DOOM = {"name":"Crackling Doom","type":"Instant","mana":"{R}{W}{B}","cmc":3,"keywords":[],"colors":["B","R","W"],"oracle":"Crackling Doom deals 2 damage to each opponent. Each opponent sacrifices a creature with the greatest power among creatures that player controls."}; // arbiter-spell on b04974fe
const CONSUMED_BY_GREED = {"name":"Consumed by Greed","type":"Instant","mana":"{1}{B}{B}","cmc":3,"keywords":["Gift"],"colors":["B"],"oracle":"Gift a card (You may promise an opponent a gift as you cast this spell. If you do, they draw a card before its other effects.)\nTarget opponent sacrifices a creature with the greatest power among creatures they control. If the gift was promised, return target creature card from your graveyard to your hand."}; // arbiter-spell on b04974fe
const WILL_OF_THE_ABZAN = {"name":"Will of the Abzan","type":"Sorcery","mana":"{3}{B}","cmc":4,"keywords":[],"colors":["B"],"oracle":"Choose one. If you control a commander as you cast this spell, you may choose both instead.\n• Any number of target opponents each sacrifice a creature with the greatest power among creatures that player controls and lose 3 life.\n• Return target creature card from your graveyard to the battlefield."}; // arbiter-spell
const EXTRACT = {"name":"Extract a Confession","type":"Sorcery","mana":"{1}{B}","cmc":2,"keywords":["Collect evidence"],"colors":["B"],"oracle":"As an additional cost to cast this spell, you may collect evidence 6. (Exile cards with total mana value 6 or greater from your graveyard.)\nEach opponent sacrifices a creature of their choice. If evidence was collected, instead each opponent sacrifices a creature with the greatest power among creatures they control."}; // arbiter-spell
const GRIZZLY_BEARS = {"name":"Grizzly Bears","type":"Creature — Bear","mana":"{1}{G}","cmc":2,"power":"2","toughness":"2","keywords":[],"colors":["G"],"oracle":""}; // native-body
const HILL_GIANT = {"name":"Hill Giant","type":"Creature — Giant","mana":"{3}{R}","cmc":4,"power":"3","toughness":"3","keywords":[],"colors":["R"],"oracle":""}; // native-body
const SIEGE_MASTODON = {"name":"Siege Mastodon","type":"Creature — Elephant","mana":"{4}{W}","cmc":5,"power":"3","toughness":"5","keywords":[],"colors":["W"],"oracle":""}; // native-body
const DARKSTEEL_MYR = {"name":"Darksteel Myr","type":"Artifact Creature — Myr","mana":"{3}","cmc":3,"power":"0","toughness":"1","keywords":["Indestructible"],"colors":[],"oracle":"Indestructible (Damage and effects that say \"destroy\" don't destroy this creature. If its toughness is 0 or less, it still dies.)"}; // native-body
const GLORIOUS_ANTHEM = {"name":"Glorious Anthem","type":"Enchantment","mana":"{1}{W}{W}","cmc":3,"keywords":[],"colors":["W"],"oracle":"Creatures you control get +1/+1."}; // native-static
const COLOSSAL_DREADMAW = {"name":"Colossal Dreadmaw","type":"Creature — Dinosaur","mana":"{4}{G}{G}","cmc":6,"power":"6","toughness":"6","keywords":["Trample"],"colors":["G"],"oracle":"Trample (This creature can deal excess combat damage to the player or planeswalker it's attacking.)"}; // native-body

// ─── harness ──────────────────────────────────────────────────────────────────
const P = (id, card, controller = "user", extra = {}) => ({ ...createPermanent({ id, card: { id: `c-${id}`, ...card }, controller, summoningSick: false }), ...extra });
const H = (id, card) => ({ ...card, id });
function board({ user = [], ai = [], hand = [], aiHand = [], pool = {}, aiPool = {}, active = "user" } = {}) {
  const g = createGameState({ userDeck: [], aiDeck: [] });
  return { ...g, turn: 5, activePlayer: active, priorityHolder: active, phase: "precombat-main", step: "main", stack: [], pendingTriggers: [], consecutivePasses: 0,
    players: { ...g.players,
      user: { ...g.players.user, battlefield: user, hand, manaPool: { ...g.players.user.manaPool, ...pool } },
      ai: { ...g.players.ai, battlefield: ai, hand: aiHand, manaPool: { ...g.players.ai.manaPool, ...aiPool } } } };
}
const cast = (s, cardId, who = "user") => {
  const offer = legalActionsForPlayer(s, who).find((a) => a.kind === "cast-spell" && a.cardId === cardId);
  expect(offer).toBeTruthy();
  return dispatchAction(s, offer);
};
const ids = (s, who) => s.players[who].battlefield.map((p) => p.id).sort();
const names = (cards) => cards.map((c) => c.name).sort();
const errors = (s) => (s.log || []).filter((e) => e.kind === "stack-resolve-error");
const DOOM_POOL = { R: 1, W: 1, B: 1 };

describe("the card and its parse", () => {
  it("⭐ classify: Crackling Doom native-spell; the greatest-power edicts behind another unread clause stay parked", () => {
    // Consumed by Greed: the target-opponent form, its gift never promised (the engine pays no optional additional cost — the shared
    // gift reading, castModifiers.stripGiftPromise), so its printed un-promised mode is the whole cast.
    expect({ doom: classifyCard(CRACKLING_DOOM), greed: classifyCard(CONSUMED_BY_GREED), abzan: classifyCard(WILL_OF_THE_ABZAN), extract: classifyCard(EXTRACT) })
      .toEqual({ doom: "native-spell", greed: "native-spell", abzan: "arbiter-spell", extract: "arbiter-spell" });
  });

  it("the program: HIGH, the damage to each opponent then the edict, no chosen target", () => {
    const p = parseEffectProgram(CRACKLING_DOOM);
    expect({ conf: programConfidence(p), ops: p.atoms.map((a) => a.op), targets: p.atoms.map((a) => a.targetType ?? null) })
      .toEqual({ conf: "high", ops: ["deal-damage", "sacrifice"], targets: ["eachOpponent", null] });
  });

  it("CONTROL — near misses stay unparsed: the greatest toughness, a count, a planeswalker pool, another sacrificer", () => {
    const atoms = (clause) => parseEffectClause(clause, "Instant")?.atoms ?? [];
    expect({
      toughness: atoms("Each opponent sacrifices a creature with the greatest toughness among creatures that player controls."),
      count: atoms("Each opponent sacrifices two creatures with the greatest power among creatures that player controls."),
      walker: atoms("Each opponent sacrifices a creature or planeswalker with the greatest power among creatures that player controls."),
      you: atoms("Sacrifice a creature with the greatest power among creatures you control."),
    }).toEqual({ toughness: [], count: [], walker: [], you: [] });
  });
});

describe("⭐ Crackling Doom — cast, resolved", () => {
  it("⭐ the opponent loses 2 and sacrifices its greatest-power creature — the Giant, not the Bear; the caster's own board is untouched", () => {
    const s0 = board({ hand: [H("doom", CRACKLING_DOOM)], pool: DOOM_POOL, user: [P("maw", COLOSSAL_DREADMAW)], ai: [P("giant", HILL_GIANT, "ai"), P("bears", GRIZZLY_BEARS, "ai")] });
    const onStack = cast(s0, "doom");
    const s = resolveTopOfStack(onStack);
    expect({ castTargets: onStack.stack[0].payload.params.targets, aiLife: s0.players.ai.life - s.players.ai.life, userLife: s0.players.user.life - s.players.user.life,
      user: ids(s, "user"), ai: ids(s, "ai"), aiGraveyard: names(s.players.ai.graveyard), pending: s.pendingChoice ?? null, errors: errors(s).length })
      .toEqual({ castTargets: [], aiLife: 2, userLife: 0, user: ["maw"], ai: ["bears"], aiGraveyard: ["Hill Giant"], pending: null, errors: 0 });
  });

  it("power is read through the layers: under the opponent's Glorious Anthem a 3/3 Giant (4/4) still out-powers the Bear (3/3); an indestructible Darksteel Myr, its only creature, is sacrificed all the same", () => {
    const s0 = board({ hand: [H("doom", CRACKLING_DOOM)], pool: DOOM_POOL, ai: [P("anthem", GLORIOUS_ANTHEM, "ai"), P("giant", HILL_GIANT, "ai"), P("bears", GRIZZLY_BEARS, "ai")] });
    const s = resolveTopOfStack(cast(s0, "doom"));
    const s1 = board({ hand: [H("doom", CRACKLING_DOOM)], pool: DOOM_POOL, ai: [P("myr", DARKSTEEL_MYR, "ai")] });
    const t = resolveTopOfStack(cast(s1, "doom"));
    expect({ anthem: ids(s, "ai"), indestructible: ids(t, "ai") }).toEqual({ anthem: ["anthem", "bears"], indestructible: [] });
  });

  it("⭐ a tie is the sacrificer's choice among the tied ONLY: the user, facing the AI's Doom with a Giant and a Mastodon (both power 3) and a Bear, is asked between the two", () => {
    const s0 = board({ active: "ai", aiHand: [H("doom", CRACKLING_DOOM)], aiPool: DOOM_POOL, user: [P("giant", HILL_GIANT), P("masto", SIEGE_MASTODON), P("bears", GRIZZLY_BEARS)] });
    const s = resolveTopOfStack(cast(s0, "doom", "ai"));
    const offered = (s.pendingChoice?.candidates || []).map((c) => c.id).sort();
    const done = s.pendingChoice ? resolveSacrificeChoice(s, "masto") : s;
    expect({ kind: s.pendingChoice?.kind ?? null, controller: s.pendingChoice?.controller ?? null, offered, user: ids(done, "user"), userGraveyard: names(done.players.user.graveyard) })
      .toEqual({ kind: "sacrifice-choice", controller: "user", offered: ["giant", "masto"], user: ["bears", "giant"], userGraveyard: ["Siege Mastodon"] });
  });

  it("Consumed by Greed: the TARGET opponent sacrifices its greatest-power creature; no gift is offered, so nothing returns", () => {
    const s0 = board({ hand: [H("greed", CONSUMED_BY_GREED)], pool: { B: 3 }, ai: [P("maw", COLOSSAL_DREADMAW, "ai"), P("bears", GRIZZLY_BEARS, "ai")] });
    const offers = legalActionsForPlayer(s0, "user").filter((a) => a.kind === "cast-spell" && a.cardId === "greed");
    const s = resolveTopOfStack(dispatchAction(s0, offers[0]));
    expect({ offers: offers.length, targets: offers[0].targets.map((t) => t.id), ai: ids(s, "ai"), userHand: s.players.user.hand.length, aiHand: s.players.ai.hand.length, errors: errors(s).length })
      .toEqual({ offers: 1, targets: ["ai"], ai: ["bears"], userHand: 0, aiHand: 0, errors: 0 });
  });

  it("an opponent with no creature only takes the damage", () => {
    const s = resolveTopOfStack(cast(board({ hand: [H("doom", CRACKLING_DOOM)], pool: DOOM_POOL }), "doom"));
    expect({ aiLife: board().players.ai.life - s.players.ai.life, pending: s.pendingChoice ?? null, errors: errors(s).length }).toEqual({ aiLife: 2, pending: null, errors: 0 });
  });
});

describe("⭐ the AI", () => {
  it("casts Crackling Doom when the opponent has a creature, and the opponent's biggest creature is the one that goes", () => {
    const s0 = board({ active: "ai", aiHand: [H("doom", CRACKLING_DOOM)], aiPool: DOOM_POOL, user: [P("maw", COLOSSAL_DREADMAW), P("bears", GRIZZLY_BEARS)] });
    const pick = pickAction(s0, "ai", legalActionsForPlayer(s0, "ai"), { archetype: "midrange" });
    const s = pick?.kind === "cast-spell" ? resolveTopOfStack(dispatchAction(s0, pick)) : s0;
    expect({ cast: pick?.kind === "cast-spell" ? pick.cardId : null, user: ids(s, "user") }).toEqual({ cast: "doom", user: ["bears"] });
  });
});
